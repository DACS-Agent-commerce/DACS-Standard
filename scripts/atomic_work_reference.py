def evaluate_vector(vector: dict[str, Any]) -> tuple[str, str]:
    """Evaluate one vector and return ``(verdict, diagnostic)``."""
    surface = vector.get("surface")
    evaluator = EVALUATORS.get(surface)
    if evaluator is None:
        return "error", f"unknown vector surface {surface!r}"
    try:
        evaluator(copy.deepcopy(vector.get("input", {})))
        return "pass", "predicate accepted"
    except Malformed as exc:
        return "error", str(exc)
    except Unknown as exc:
        return "indeterminate", str(exc)
    except (Invalid, ValueError, TypeError, KeyError, IndexError) as exc:
        return "fail", str(exc)
    except Exception as exc:  # pragma: no cover - fail closed for malformed corpus
        return "error", f"{type(exc).__name__}: {exc}"


def vector_hash(vectors: list[dict[str, Any]]) -> str:
    """The candidate corpus hash: SHA-256 over RFC 8785 JCS of ``vectors``."""
    return sha256_hex(jcs_bytes(vectors))


def render_set(data: dict[str, Any]) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"
