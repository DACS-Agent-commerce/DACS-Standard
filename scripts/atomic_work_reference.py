_SCHEMA_VALIDATORS: dict[str, Draft202012Validator] | None = None


def _schema_validators() -> dict[str, Draft202012Validator]:
    """Load the published Atomic schemas once for mandatory ingress checks."""
    global _SCHEMA_VALIDATORS
    if _SCHEMA_VALIDATORS is not None:
        return _SCHEMA_VALIDATORS
    schema_dir = ROOT / "spec" / "schemas"
    schemas = {
        path.name: json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(schema_dir.glob("atomic-*.schema.json"))
    }
    registry = Registry()
    for name, schema in schemas.items():
        resource = Resource.from_contents(schema)
        registry = registry.with_resource(schema["$id"], resource)
        registry = registry.with_resource(name, resource)
    _SCHEMA_VALIDATORS = {
        name: Draft202012Validator(schema, registry=registry)
        for name, schema in schemas.items()
    }
    return _SCHEMA_VALIDATORS


def validate_schema(value: Any, schema_name: str) -> None:
    """Fail closed when a value does not satisfy its normative JSON Schema."""
    validator = _schema_validators().get(schema_name)
    if validator is None:
        raise Invalid(f"normative schema unavailable: {schema_name}")
    error = next(iter(validator.iter_errors(value)), None)
    if error is not None:
        location = "/".join(str(part) for part in error.absolute_path) or "<root>"
        raise Invalid(f"{schema_name}:{location}: {error.message}")


def jcs_bytes(value: Any) -> bytes:
    return canonicalize(value).encode("utf-8")


def sha256(raw: bytes) -> bytes:
    return hashlib.sha256(raw).digest()


def sha256_hex(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def b64u(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


def b64u_decode(value: str) -> bytes:
    if (
        not isinstance(value, str)
        or not re.fullmatch(r"[A-Za-z0-9_-]*", value)
        or len(value) % 4 == 1
    ):
        raise Invalid("base64url value must be an unpadded string")
    try:
        decoded = base64.b64decode(
            value.encode("ascii") + b"=" * (-len(value) % 4),
            altchars=b"-_", validate=True,
        )
    except (ValueError, UnicodeEncodeError) as exc:
        raise Invalid("invalid base64url value") from exc
    if b64u(decoded) != value:
        raise Invalid("non-canonical base64url encoding")
    return decoded


def _ed25519_public_bytes(value: Any) -> bytes:
    raw = b64u_decode(value)
    if len(raw) != 32:
        raise Invalid("Ed25519 public key must be exactly 32 bytes")
    return raw


def _ed25519_signature_bytes(value: Any) -> bytes:
    raw = b64u_decode(value)
    if len(raw) != 64:
        raise Invalid("Ed25519 signature must be exactly 64 bytes")
    return raw


# ---- dependency-free Ed25519 (RFC 8032 reference equations) -----------------

_Q = 2**255 - 19
_L = 2**252 + 27742317777372353535851937790883648493
_D = (-121665 * pow(121666, _Q - 2, _Q)) % _Q
_I = pow(2, (_Q - 1) // 4, _Q)


def _xrecover(y: int) -> int:
    xx = (y * y - 1) * pow(_D * y * y + 1, _Q - 2, _Q)
    x = pow(xx, (_Q + 3) // 8, _Q)
    if (x * x - xx) % _Q != 0:
        x = (x * _I) % _Q
    if x & 1:
        x = _Q - x
    return x


_BY = (4 * pow(5, _Q - 2, _Q)) % _Q
_BX = _xrecover(_BY)
_B = (_BX, _BY, 1, (_BX * _BY) % _Q)
_IDENTITY = (0, 1, 1, 0)


def _edwards(
    p: tuple[int, int, int, int], q: tuple[int, int, int, int]
) -> tuple[int, int, int, int]:
    """Complete extended-coordinate addition for a=-1 Edwards25519."""
    x1, y1, z1, t1 = p
    x2, y2, z2, t2 = q
    a = ((y1 - x1) * (y2 - x2)) % _Q
    b = ((y1 + x1) * (y2 + x2)) % _Q
    c = (2 * _D * t1 * t2) % _Q
    d = (2 * z1 * z2) % _Q
    e = (b - a) % _Q
    f = (d - c) % _Q
    g = (d + c) % _Q
    h = (b + a) % _Q
    return (e * f % _Q, g * h % _Q, f * g % _Q, e * h % _Q)


def _edwards_double(p: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    x, y, z, _ = p
    a = x * x % _Q
    b = y * y % _Q
    c = 2 * z * z % _Q
    d = (-a) % _Q
    e = ((x + y) * (x + y) - a - b) % _Q
    g = (d + b) % _Q
    f = (g - c) % _Q
    h = (d - b) % _Q
    return (e * f % _Q, g * h % _Q, f * g % _Q, e * h % _Q)


def _scalarmult(
    p: tuple[int, int, int, int], scalar: int
) -> tuple[int, int, int, int]:
    result = _IDENTITY
    addend = p
    while scalar:
        if scalar & 1:
            result = _edwards(result, addend)
        addend = _edwards_double(addend)
        scalar >>= 1
    return result


def _encode_point(p: tuple[int, int, int, int]) -> bytes:
    x, y, z, _ = p
    z_inv = pow(z, _Q - 2, _Q)
    x = x * z_inv % _Q
    y = y * z_inv % _Q
    return int.to_bytes(y | ((x & 1) << 255), 32, "little")


def _decode_point(encoded: bytes) -> tuple[int, int, int, int]:
    if len(encoded) != 32:
        raise Invalid("Ed25519 point is not 32 bytes")
    value = int.from_bytes(encoded, "little")
    y = value & ((1 << 255) - 1)
    if y >= _Q:
        raise Invalid("non-canonical Ed25519 point")
    x = _xrecover(y)
    if (x & 1) != (value >> 255):
        x = _Q - x
    p = (x, y, 1, x * y % _Q)
    if _encode_point(p) != encoded:
        raise Invalid("non-canonical Ed25519 encoding")
    return p


def _secret_scalar(seed: bytes) -> tuple[int, bytes]:
    if len(seed) != 32:
        raise ValueError("Ed25519 seed must be 32 bytes")
    digest = hashlib.sha512(seed).digest()
    scalar_bytes = bytearray(digest[:32])
    scalar_bytes[0] &= 248
    scalar_bytes[31] &= 63
    scalar_bytes[31] |= 64
    return int.from_bytes(scalar_bytes, "little"), digest[32:]


def ed25519_public_key(seed: bytes) -> bytes:
    scalar, _ = _secret_scalar(seed)
    return _encode_point(_scalarmult(_B, scalar))


def ed25519_sign(seed: bytes, message: bytes) -> bytes:
    scalar, prefix = _secret_scalar(seed)
    public = ed25519_public_key(seed)
    r = int.from_bytes(hashlib.sha512(prefix + message).digest(), "little") % _L
    encoded_r = _encode_point(_scalarmult(_B, r))
    challenge = int.from_bytes(
        hashlib.sha512(encoded_r + public + message).digest(), "little"
    ) % _L
    s = (r + challenge * scalar) % _L
    return encoded_r + int.to_bytes(s, 32, "little")


def ed25519_verify(public: bytes, message: bytes, signature: bytes) -> bool:
    if len(public) != 32 or len(signature) != 64:
        return False
    encoded_r, encoded_s = signature[:32], signature[32:]
    s = int.from_bytes(encoded_s, "little")
    if s >= _L:
        return False
    try:
        a = _decode_point(public)
        r = _decode_point(encoded_r)
    except Invalid:
        return False
    challenge = int.from_bytes(
        hashlib.sha512(encoded_r + public + message).digest(), "little"
    ) % _L
    # Cofactor multiplication rejects small-order malleability while retaining
    # the compact affine reference implementation.
    left = _scalarmult(_B, (s * 8) % _L)
    right = _scalarmult(_edwards(r, _scalarmult(a, challenge)), 8)
    return (
        left[0] * right[2] % _Q == right[0] * left[2] % _Q
        and left[1] * right[2] % _Q == right[1] * left[2] % _Q
    )


def _claim_parts(claim: Any) -> tuple[str, str, tuple[tuple[str, str], ...]]:
    """Parse one CF-2 canonical ClaimReference without repairing its bytes."""
    if not isinstance(claim, str) or not CLAIM_REFERENCE.fullmatch(claim):
        raise Invalid("signer is not a canonical ClaimReference string")
    scheme, remainder = claim.split(":", 1)
    identifier, separator, encoded_parameters = remainder.partition("?")
    if (
        not identifier
        or unicodedata.normalize("NFC", identifier) != identifier
        or any(ord(character) < 0x20 or ord(character) == 0x7F for character in identifier)
    ):
        raise Invalid("ClaimReference identifier is not canonical NFC text")
    # The executable profile implements only the identifier profiles exercised
    # by its public fixtures. Rejecting other schemes is safer than pretending
    # generic string parsing implements the scheme-specific CF-2 registry.
    if scheme == "did":
        if not _SYNTHETIC_DID_IDENTIFIER.fullmatch(identifier):
            raise Invalid("test verifier only implements canonical did:dacs:test identifiers")
    elif scheme == "domain":
        labels = identifier.split(".")
        if (
            len(identifier.encode("ascii", "ignore")) != len(identifier)
            or len(identifier) > 253
            or len(labels) < 2
            or any(not _DOMAIN_LABEL.fullmatch(label) for label in labels)
        ):
            raise Invalid("domain ClaimReference is not a canonical lowercase A-label hostname")
    else:
        raise Invalid(f"test verifier does not implement CF-2 identifier rules for {scheme!r}")
    parameters: list[tuple[str, str]] = []
    if separator:
        if not encoded_parameters:
            raise Invalid("ClaimReference parameter list is empty")
        for item in encoded_parameters.split("&"):
            if item.count("=") != 1:
                raise Invalid("ClaimReference parameter is not key=value")
            key, value = item.split("=", 1)
            if not key or unicodedata.normalize("NFC", item) != item:
                raise Invalid("ClaimReference parameter is not canonical NFC text")
            for component in (key, value):
                index = 0
                while index < len(component):
                    if component[index] == "%":
                        if not _PERCENT_ESCAPE.match(component, index):
                            raise Invalid("ClaimReference percent escape is not uppercase canonical form")
                        index += 3
                    else:
                        if component[index] in ":?&=":
                            raise Invalid("ClaimReference reserved parameter character is not encoded")
                        index += 1
            parameters.append((key, value))
        keys = [key for key, _ in parameters]
        if len(keys) != len(set(keys)) or keys != sorted(keys):
            raise Invalid("ClaimReference parameters are not canonical and unique")
    return scheme, identifier, tuple(parameters)


def claim_key(claim: Any) -> str:
    """Return the exact CF-2 canonical byte form used in signed material."""
    _claim_parts(claim)
    return claim


def claim_identity(claim: Any) -> tuple[str, str]:
    """Return the CF-3 identity; advisory parameters intentionally disappear."""
    scheme, identifier, _ = _claim_parts(claim)
    return scheme, identifier


def claim_equal(left: Any, right: Any) -> bool:
    return claim_identity(left) == claim_identity(right)


def _public_key_for_claim(public_keys: dict[str, str], claim: Any) -> str | None:
    """Resolve keys by CF-3 identity while rejecting ambiguous aliases."""
    canonical = claim_key(claim)
    if canonical in public_keys:
        return public_keys[canonical]
    identity = claim_identity(canonical)
    matches = [
        key for candidate, key in public_keys.items()
        if claim_identity(candidate) == identity
    ]
    if len(matches) > 1:
        raise Invalid("multiple authenticated keys resolve to one ClaimReference identity")
    return matches[0] if matches else None


def require_signer(value: dict[str, Any], expected: str, field: str = "signature") -> None:
    """Require a verified embedded object to name its authenticated authority."""
    if not claim_equal(value.get(field, {}).get("signer"), expected):
        raise Invalid(f"{field} signer is not the authenticated authority")


def _signed_hash(value: dict[str, Any], excluded: Iterable[str]) -> str:
    if not _is_pure_json(value):
        raise Invalid("signed value is not NFC-normalized safe-integer JSON")
    unsigned = {k: v for k, v in value.items() if k not in set(excluded)}
    return sha256_hex(jcs_bytes(unsigned))


def sign_embedded(
    value: dict[str, Any], signer: str, seed: bytes, domain: bytes,
    *, field: str = "signature", excluded: Iterable[str] | None = None,
) -> dict[str, Any]:
    """Return a copy carrying a deterministic signature over its unsigned hash."""
    out = copy.deepcopy(value)
    excluded_fields = tuple(excluded or (field,))
    digest = _signed_hash(out, excluded_fields)
    out[field] = {
        "algorithm": "ed25519",
        "signer": signer,
        "value": b64u(ed25519_sign(seed, domain + digest.encode("ascii"))),
    }
    return out


def verify_embedded(
    value: dict[str, Any], public_keys: dict[str, str], domain: bytes,
    *, field: str = "signature", excluded: Iterable[str] | None = None,
) -> None:
    sig = value.get(field)
    if not isinstance(sig, dict):
        raise Unknown(f"missing {field}")
    if sig.get("algorithm") != "ed25519":
        raise Invalid("unsupported signature algorithm")
    signer = claim_key(sig.get("signer"))
    encoded_public = _public_key_for_claim(public_keys, signer)
    if encoded_public is None:
        raise Unknown(f"no authenticated key for {signer}")
    excluded_fields = tuple(excluded or (field,))
    digest = _signed_hash(value, excluded_fields)
    message = domain + digest.encode("ascii")
    if not ed25519_verify(
        _ed25519_public_bytes(encoded_public), message,
        _ed25519_signature_bytes(sig.get("value", "")),
    ):
        raise Invalid(f"invalid {field}")


def verify_encoded_evidence(
    evidence: dict[str, Any], expected_kind: str,
    public_keys: dict[str, str], domain: bytes, *, expected_signer: str | None = None,
) -> dict[str, Any]:
    """Resolve a normative ``{kind,value}`` evidence reference and verify it."""
    if not isinstance(evidence, dict):
        raise Unknown(f"missing {expected_kind} evidence")
    if evidence.get("kind") != expected_kind:
        raise Invalid(f"unexpected evidence kind {evidence.get('kind')!r}")
    try:
        decoded = json.loads(b64u_decode(evidence.get("value", "")).decode("utf-8"))
    except (Invalid, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise Invalid(f"invalid encoded {expected_kind} evidence") from exc
    if not isinstance(decoded, dict):
        raise Invalid(f"decoded {expected_kind} evidence is not an object")
    verify_embedded(decoded, public_keys, domain)
    if expected_signer is not None:
        require_signer(decoded, expected_signer)
    return decoded


# ---- normative derivations ---------------------------------------------------

def work_id(intent: dict[str, Any]) -> str:
    return sha256_hex(WORK_DOMAIN + jcs_bytes(intent))


def authorization_hash(authorization: dict[str, Any]) -> str:
    return _signed_hash(authorization, ("value",))


def sign_authorization(authorization: dict[str, Any], seed: bytes) -> dict[str, Any]:
    out = copy.deepcopy(authorization)
    out.pop("value", None)
    digest = authorization_hash(out)
    out["value"] = b64u(ed25519_sign(seed, AUTH_DOMAIN + digest.encode("ascii")))
    return out


def receipt_hash(receipt: dict[str, Any]) -> str:
    return sha256_hex(jcs_bytes(receipt))


def operation_leaf_hash(leaf: dict[str, Any]) -> bytes:
    return sha256(b"\x00" + OP_RECEIPT_DOMAIN + jcs_bytes(leaf))


def merkle_root_from_hashes(hashes: list[bytes]) -> bytes:
    if not hashes:
        return sha256(b"")
    if len(hashes) == 1:
        return hashes[0]
    split = 1 << ((len(hashes) - 1).bit_length() - 1)
    return sha256(
        b"\x01"
        + merkle_root_from_hashes(hashes[:split])
        + merkle_root_from_hashes(hashes[split:])
    )


def operation_receipt_root(leaves: list[dict[str, Any]]) -> str:
    return merkle_root_from_hashes([operation_leaf_hash(v) for v in leaves]).hex()


def evaluate_merkle(data: dict[str, Any]) -> None:
    leaves = data.get("leaves")
    if not isinstance(leaves, list):
        raise Invalid("Merkle leaves unavailable")
    if data.get("claimedRoot") != operation_receipt_root(leaves):
        raise Invalid("operation receipt primitive root mismatch")
    for index, leaf in enumerate(leaves):
        if not verify_inclusion(leaf, inclusion_path(leaves, index), data["claimedRoot"]):
            raise Invalid("operation receipt primitive inclusion failed")


def _largest_split(count: int) -> int:
    return 1 << ((count - 1).bit_length() - 1)


def inclusion_path(leaves: list[dict[str, Any]], index: int) -> list[dict[str, str]]:
    if index < 0 or index >= len(leaves):
        raise IndexError(index)

    def walk(hashes: list[bytes], idx: int) -> tuple[bytes, list[dict[str, str]]]:
        if len(hashes) == 1:
            return hashes[0], []
        split = _largest_split(len(hashes))
        if idx < split:
            root, path = walk(hashes[:split], idx)
            sibling = merkle_root_from_hashes(hashes[split:])
            return sha256(b"\x01" + root + sibling), path + [{"side": "right", "hash": sibling.hex()}]
        root, path = walk(hashes[split:], idx - split)
        sibling = merkle_root_from_hashes(hashes[:split])
        return sha256(b"\x01" + sibling + root), path + [{"side": "left", "hash": sibling.hex()}]

    _, result = walk([operation_leaf_hash(v) for v in leaves], index)
    return result


def verify_inclusion(leaf: dict[str, Any], path: list[dict[str, str]], root: str) -> bool:
    value = operation_leaf_hash(leaf)
    for item in path:
        try:
            sibling = bytes.fromhex(item["hash"])
        except (KeyError, ValueError):
            return False
        if len(sibling) != 32:
            return False
        if item.get("side") == "right":
            value = sha256(b"\x01" + value + sibling)
        elif item.get("side") == "left":
            value = sha256(b"\x01" + sibling + value)
        else:
            return False
    return value.hex() == root


def state_root(state: dict[str, Any]) -> str:
    return sha256_hex(jcs_bytes(state))


def conflict_digest(conflict: dict[str, Any]) -> str:
    return sha256_hex(SLOT_DOMAIN + jcs_bytes(conflict))


_OPERATION_REF_FIELDS = {
    "kind", "networkId", "workId", "operationIndex", "operationId", "operationKind"
}


def settlement_id(operation_ref: dict[str, Any]) -> str:
    if not isinstance(operation_ref, dict) or not _OPERATION_REF_FIELDS.issubset(
        operation_ref
    ):
        raise Invalid("operationRef lacks the required v1 identity members")
    projected = {field: operation_ref[field] for field in (
        "kind", "networkId", "workId", "operationIndex", "operationId",
        "operationKind",
    )}
    if (
        projected["kind"] != "demos-work-operation-v1"
        or not isinstance(projected["networkId"], str)
        or not projected["networkId"]
        or not isinstance(projected["workId"], str)
        or not HEX_64.fullmatch(projected["workId"])
        or not isinstance(projected["operationIndex"], int)
        or isinstance(projected["operationIndex"], bool)
        or projected["operationIndex"] < 0
        or not isinstance(projected["operationId"], str)
        or not OP_ID.fullmatch(projected["operationId"])
        or projected["operationKind"] not in OP_KINDS
    ):
        raise Invalid("operationRef required v1 identity member is invalid")
    return sha256_hex(SETTLEMENT_ID_DOMAIN + jcs_bytes(projected))


def cf4_encode(value: str) -> str:
    out = value
    for char, encoded in (("%", "%25"), (":", "%3A"), ("?", "%3F"), ("&", "%26"), ("=", "%3D")):
        out = out.replace(char, encoded)
    return out


def cf4_decode(value: str) -> str:
    if re.search(r"%(?![0-9A-F]{2})", value):
        raise Malformed("non-canonical CF-4 escape")
    decoded = value
    for encoded, char in (("%3A", ":"), ("%3F", "?"), ("%26", "&"), ("%3D", "="), ("%25", "%")):
        decoded = decoded.replace(encoded, char)
    if cf4_encode(decoded) != value:
        raise Malformed("non-canonical CF-4 segment")
    return decoded


def _canonical_uint(value: str, label: str) -> int:
    if not isinstance(value, str) or not re.fullmatch(r"0|[1-9][0-9]*", value):
        raise Malformed(f"non-canonical {label}")
    number = int(value)
    if number > SAFE_INT_MAX:
        raise Malformed(f"unsafe {label}")
    return number


def parse_pc2_address(address: str) -> dict[str, Any]:
    if not isinstance(address, str):
        raise Malformed("PC2 address is not a string")
    parts = address.split(":")
    if len(parts) != 5 or parts[:2] != ["dacs4", "payment"]:
        raise Malformed("invalid ordinary PC2 address shape")
    if not JOB_ID.fullmatch(parts[2]):
        raise Malformed("PC2 jobId is not a ULID")
    return {
        "jobId": parts[2], "railId": cf4_decode(parts[3]),
        "phaseIndex": _canonical_uint(parts[4], "phaseIndex"),
    }


def atomic_evidence_address(evidence: dict[str, Any], generation: int | None = None) -> str:
    identity = settlement_id(evidence["operationRef"])
    if evidence.get("phase") == "pay-dem":
        if not isinstance(generation, int) or isinstance(generation, bool) or generation < 0:
            raise Malformed("payment generation unavailable")
        return (
            f"dacs4:payment:{evidence['jobId']}:{cf4_encode(evidence['railId'])}:"
            f"{evidence['phaseIndex']}:atomic:{generation}:{identity}"
        )
    if evidence.get("phase") == "deliver-storage-program":
        return f"dacs4:delivery:{evidence['jobId']}:{evidence['phaseIndex']}:atomic:{identity}"
    raise Invalid("unsupported Atomic evidence phase")


def verify_atomic_evidence_address(
    address: str, evidence: dict[str, Any], generation: int | None = None
) -> None:
    if not isinstance(address, str):
        raise Malformed("Atomic evidence address is not a string")
    parts = address.split(":")
    if evidence.get("phase") == "pay-dem":
        if len(parts) != 8 or parts[:2] != ["dacs4", "payment"] or parts[5] != "atomic":
            raise Malformed("invalid Atomic payment address shape")
        if not JOB_ID.fullmatch(parts[2]):
            raise Malformed("Atomic payment jobId is not a ULID")
        cf4_decode(parts[3])
        _canonical_uint(parts[4], "phaseIndex")
        parsed_generation = _canonical_uint(parts[6], "generation")
        if parsed_generation != generation:
            raise Invalid("Atomic payment address generation mismatch")
        if not HEX_64.fullmatch(parts[7]):
            raise Malformed("Atomic payment settlement ID is not lowercase hex")
    elif evidence.get("phase") == "deliver-storage-program":
        if len(parts) != 6 or parts[:2] != ["dacs4", "delivery"] or parts[4] != "atomic":
            raise Malformed("invalid Atomic delivery address shape")
        if not JOB_ID.fullmatch(parts[2]):
            raise Malformed("Atomic delivery jobId is not a ULID")
        _canonical_uint(parts[3], "phaseIndex")
        if not HEX_64.fullmatch(parts[5]):
            raise Malformed("Atomic delivery settlement ID is not lowercase hex")
    else:
        raise Invalid("unsupported Atomic evidence phase")
    if address != atomic_evidence_address(evidence, generation):
        raise Invalid("Atomic evidence address mismatch")


def _is_pure_json(value: Any) -> bool:
    if value is None or isinstance(value, bool):
        return True
    if isinstance(value, str):
        return unicodedata.normalize("NFC", value) == value
    if isinstance(value, int) and not isinstance(value, bool):
        return abs(value) <= SAFE_INT_MAX
    if isinstance(value, list):
        return all(_is_pure_json(v) for v in value)
    if isinstance(value, dict):
        return all(
            isinstance(k, str)
            and unicodedata.normalize("NFC", k) == k
            and _is_pure_json(v)
            for k, v in value.items()
        )
    return False


def _json_equal(left: Any, right: Any) -> bool:
    """Compare pure JSON without Python's ``False == 0`` coercion."""
    return (
        type(left) is type(right)
        and _is_pure_json(left)
        and _is_pure_json(right)
        and jcs_bytes(left) == jcs_bytes(right)
    )


def _generation(value: Any, label: str) -> int:
    if (
        not isinstance(value, int)
        or isinstance(value, bool)
        or not (0 <= value <= SAFE_INT_MAX)
    ):
        raise Invalid(f"{label} generation is not a non-negative safe integer")
    return value


def _ordered_unique(values: list[str], ordering: tuple[str, ...] = ROLE_ORDER) -> bool:
    if len(values) != len(set(values)) or any(v not in ordering for v in values):
        return False
    return [ordering.index(v) for v in values] == sorted(ordering.index(v) for v in values)


def validate_intent(intent: dict[str, Any], claimed: str | None = None) -> None:
    if not isinstance(intent, dict) or not _is_pure_json(intent):
        raise Invalid("intent is not pure safe-integer JSON")
    validate_schema(intent, "atomic-dacs-work-intent-v1.schema.json")
    if intent.get("workVersion") != "1":
        raise Invalid("unsupported workVersion")
    if intent.get("profile") not in {"dacs-purchase-v1", "dacs-completion-v1"}:
        raise Invalid("unsupported profile")
    for field in ("executionProfile", "networkId", "railId", "jobId"):
        if not isinstance(intent.get(field), str) or not intent[field]:
            raise Invalid(f"invalid {field}")
    if not JOB_ID.fullmatch(intent["jobId"]):
        raise Invalid("jobId is not a canonical uppercase ULID")
    if not isinstance(intent.get("phaseIndex"), int) or isinstance(intent["phaseIndex"], bool):
        raise Invalid("phaseIndex is not an integer")
    if not isinstance(intent.get("expiresAt"), int) or isinstance(intent["expiresAt"], bool):
        raise Invalid("expiresAt is not an integer")
    roster = intent.get("roleRoster")
    if not isinstance(roster, list):
        raise Invalid("roleRoster missing")
    roles = [r.get("role") for r in roster if isinstance(r, dict)]
    if len(roles) != len(roster) or not _ordered_unique(roles):
        raise Invalid("roleRoster is not canonical and unique")
    for binding in roster:
        claim_key(binding.get("signer"))
    operations = intent.get("operations")
    if not isinstance(operations, list) or not operations:
        raise Invalid("operations missing")
    seen: set[str] = set()
    for index, operation in enumerate(operations):
        if not isinstance(operation, dict):
            raise Invalid("operation is not an object")
        operation_id = operation.get("operationId")
        if not isinstance(operation_id, str) or not OP_ID.fullmatch(operation_id):
            raise Invalid("invalid operationId")
        if operation_id in seen:
            raise Invalid("duplicate operationId")
        if operation.get("kind") not in OP_KINDS:
            raise Invalid("unknown operation kind")
        if operation.get("critical") is not True:
            raise Invalid("non-critical v1 operation")
        dependencies = operation.get("dependsOn")
        if not isinstance(dependencies, list) or len(dependencies) != len(set(dependencies)):
            raise Invalid("invalid dependency list")
        if any(dep not in seen for dep in dependencies):
            raise Invalid("dependency is unknown, self, or not earlier")
        required = operation.get("requiredRoles")
        if not isinstance(required, list) or not _ordered_unique(required):
            raise Invalid("requiredRoles is not canonical and unique")
        if any(role not in roles for role in required):
            raise Invalid("required role absent from roster")
        payload = operation.get("payload")
        if not isinstance(payload, dict) or "$runtime" in payload:
            raise Invalid("payload is not a pure portable data value")
        seen.add(operation_id)
    derived = work_id(intent)
    if claimed is not None and claimed != derived:
        raise Invalid("claimed workId does not match canonical bytes")
    if "priorFailureReceiptCommitment" in intent and not (
        isinstance(intent["priorFailureReceiptCommitment"], str)
        and HEX_64.fullmatch(intent["priorFailureReceiptCommitment"])
    ):
        raise Invalid("priorFailureReceiptCommitment is not a lowercase SHA-256 hash")


def verify_capability(
    capability: dict[str, Any], public_keys: dict[str, str],
    expected_network_authority: str | None = None,
) -> None:
    if not _is_pure_json(capability):
        raise Invalid("capability is not NFC-normalized safe-integer JSON")
    validate_schema(capability, "atomic-work-capability-v1.schema.json")
    if expected_network_authority is None:
        raise Unknown("independently pinned network capability authority unavailable")
    if not claim_equal(capability.get("networkAuthority"), expected_network_authority):
        raise Invalid("capability network authority differs from trusted registry")
    unsigned = {k: v for k, v in capability.items() if k != "evidence"}
    attestation = verify_encoded_evidence(
        capability.get("evidence"), "test-network-capability-attestation",
        public_keys, _CAPABILITY_TEST_DOMAIN,
        expected_signer=expected_network_authority,
    )
    if attestation.get("capabilityHash") != sha256_hex(jcs_bytes(unsigned)):
        raise Invalid("capability attestation hash mismatch")
    if capability.get("capabilityVersion") != "1":
        raise Invalid("unsupported capability")
    claim_key(capability.get("networkAuthority"))
    if capability.get("workVersions") != ["1"]:
        raise Invalid("capability does not admit Work v1")
    if capability.get("operationKinds") != sorted(OP_KINDS):
        raise Invalid("capability operation-kind list is not the exact canonical v1 list")
    if capability.get("payloadSchemas") != PAYLOAD_SCHEMAS:
        raise Invalid("capability payload-schema map is not the exact v1 map")
    if capability.get("authorizationAlgorithms") != ["ed25519"]:
        raise Invalid("Atomic Work v1 admits only the canonical Ed25519 suite")
    if not all(
        isinstance(capability.get(field), str) and capability[field]
        for field in (
            "networkId", "executionProfile", "proofProfile", "validatorSetId",
        )
    ):
        raise Invalid("capability identity/proof binding is incomplete")
    limits = capability.get("limits")
    if not isinstance(limits, dict) or any(
        not isinstance(limits.get(k), int) or isinstance(limits.get(k), bool) or limits[k] <= 0
        for k in (
            "maxCanonicalBytes", "maxOperations", "maxExecutionTimeMs",
            "maxProofBytes",
        )
    ):
        raise Invalid("invalid capability limits")
    if limits.get("feeRule") != "test-fixed-fee":
        raise Invalid("reference verifier does not implement the advertised fee rule")


def validate_payload_schemas(
    intent: dict[str, Any], capability: dict[str, Any]
) -> None:
    """Validate every operation against the profile's advertised closed v1 schema."""
    if capability.get("executionProfile") != intent.get("executionProfile"):
        raise Invalid("payload schema execution profile mismatch")
    advertised = capability.get("payloadSchemas")
    if not isinstance(advertised, dict):
        raise Invalid("capability payloadSchemas missing")
    admitted = capability.get("operationKinds")
    if admitted != sorted(OP_KINDS):
        raise Invalid("capability operation-kind list is not the exact canonical v1 list")
    if advertised != PAYLOAD_SCHEMAS:
        raise Invalid("capability payload-schema map is not the exact v1 map")

    for operation in intent["operations"]:
        kind = operation["kind"]
        payload = operation["payload"]
        keys = set(payload)
        if kind == "assert-artifact":
            valid = keys == {"artifact"} and isinstance(payload.get("artifact"), dict)
        elif kind == "storage-program-put":
            write_condition = payload.get("writeCondition")
            condition_valid = isinstance(write_condition, dict) and (
                write_condition == {"kind": "create-only"}
                or (
                    set(write_condition) == {"kind", "expectedContentHash"}
                    and write_condition.get("kind") == "compare-and-set"
                    and isinstance(write_condition.get("expectedContentHash"), str)
                    and bool(HEX_64.fullmatch(write_condition["expectedContentHash"]))
                )
            )
            artifact_shape = (
                keys == {"artifact", "logicalAddress", "writeCondition"}
                and isinstance(payload.get("artifact"), dict)
            )
            bytes_shape = (
                keys == {"bytes", "contentHash", "logicalAddress", "writeCondition"}
                and isinstance(payload.get("bytes"), str)
                and isinstance(payload.get("contentHash"), str)
                and bool(HEX_64.fullmatch(payload["contentHash"]))
            )
            if bytes_shape:
                decoded_bytes = b64u_decode(payload["bytes"])
                if sha256_hex(decoded_bytes) != payload["contentHash"]:
                    raise Invalid(
                        "storage-program-put contentHash does not match decoded bytes"
                    )
            valid = condition_valid and (artifact_shape or bytes_shape) and isinstance(
                payload.get("logicalAddress"), str
            ) and bool(payload["logicalAddress"])
        elif kind == "payment-slot-cas":
            valid = (
                keys == {"slotKey", "expected", "conflictDigest"}
                and isinstance(payload.get("slotKey"), dict)
                and set(payload["slotKey"]) == {"networkId", "railId", "jobId", "phaseIndex"}
                and isinstance(payload.get("expected"), dict)
                and set(payload["expected"]) == {"state", "generation"}
                and payload["expected"].get("state") in {"vacant", "rolled-back"}
                and isinstance(payload["expected"].get("generation"), int)
                and not isinstance(payload["expected"].get("generation"), bool)
                and isinstance(payload.get("conflictDigest"), str)
                and bool(HEX_64.fullmatch(payload["conflictDigest"]))
            )
        elif kind == "native-dem-transfer":
            valid = keys == {"from", "to", "asset", "amount"} and all(
                isinstance(payload.get(field), str) and bool(payload[field])
                for field in ("from", "to", "asset", "amount")
            )
        elif kind == "assert-work-receipt":
            valid = keys == {"receipt"} and isinstance(payload.get("receipt"), dict)
        else:  # validate_intent rejects this first; retain fail-closed locality.
            valid = False
        if not valid:
            raise Invalid(f"payload does not conform to {advertised.get(kind)!r}")


def consume_capability_for_intent(
    intent: dict[str, Any], capability: dict[str, Any],
    public_keys: dict[str, str], expected_network_authority: str | None,
    expected_proof_profile: str | None,
) -> None:
    """Verify and scope an authenticated capability at every Work trust boundary."""
    validate_intent(intent)
    verify_capability(capability, public_keys, expected_network_authority)
    if capability.get("networkId") != intent.get("networkId"):
        raise Invalid("capability networkId does not admit the Work intent")
    if capability.get("executionProfile") != intent.get("executionProfile"):
        raise Invalid("capability executionProfile does not admit the Work intent")
    if intent.get("workVersion") not in capability.get("workVersions", []):
        raise Invalid("capability workVersions do not admit the Work intent")
    if intent.get("profile") not in capability.get("profiles", []):
        raise Invalid("capability profiles do not admit the Work intent")
    if not isinstance(expected_proof_profile, str) or not expected_proof_profile:
        raise Unknown("independently selected proof profile unavailable")
    if capability.get("proofProfile") != expected_proof_profile:
        raise Invalid("capability proofProfile differs from the selected verifier profile")
    validate_payload_schemas(intent, capability)


def evaluate_capability(data: dict[str, Any]) -> None:
    stage = data.get("stage")
    fallback = data.get("fallback", False)
    capability = data.get("capability")
    verified = False
    if isinstance(capability, dict):
        try:
            verify_capability(capability, data["publicKeys"], data.get("expectedNetworkAuthority"))
            intent = data.get("intent")
            if isinstance(intent, dict):
                consume_capability_for_intent(
                    intent, capability, data["publicKeys"],
                    data.get("expectedNetworkAuthority"), data.get("expectedProofProfile"),
                )
                verified = True
            else:
                verified = (
                    capability.get("networkId") == data.get("networkId")
                    and data.get("executionProfile") == capability.get("executionProfile")
                    and data.get("profile") in capability.get("profiles", [])
                    and data.get("expectedProofProfile") == capability.get("proofProfile")
                )
        except (Invalid, Unknown):
            verified = False
    if data.get("mode") == "legacy":
        if stage != "pre-sign":
            raise Invalid("legacy fallback after Atomic signature/submission")
        if not fallback:
            raise Invalid("legacy mode not selected")
        return
    if not verified:
        if stage == "pre-sign" and fallback:
            return
        raise Invalid("Atomic profile lacks verified matching capability")
    if fallback and stage in {"signed", "submitted"}:
        raise Invalid("silent fallback after Atomic work authorization")
    if data.get("businessWorks") != 2 or data.get("auditTail") is not True:
        raise Invalid("profile is two business Works plus an audit tail")
    if data.get("claimsExactlyTwoLifecycleTransactions") is True:
        raise Invalid("full lifecycle is not exactly two transactions")


def verify_authorizations(
    intent: dict[str, Any], authorizations: list[dict[str, Any]], public_keys: dict[str, str],
    authority: dict[str, Any] | None = None, capability: dict[str, Any] | None = None,
    expected_network_authority: str | None = None,
    expected_proof_profile: str | None = None,
    expected_rail_registry_authority: str | None = None,
) -> None:
    if not isinstance(capability, dict):
        raise Unknown("verified capability unavailable for authorization")
    consume_capability_for_intent(
        intent, capability, public_keys, expected_network_authority,
        expected_proof_profile,
    )
    _profile_shape(intent, intent["profile"])
    if not isinstance(authority, dict):
        raise Unknown("independently authenticated role authority unavailable")
    authority_context = _verified_authority_context(
        intent, authority, public_keys, capability, expected_proof_profile,
        expected_rail_registry_authority,
    )
    derived = work_id(intent)
    roster = {r["role"]: r["signer"] for r in intent["roleRoster"]}
    if any(
        not claim_equal(roster.get(role), authority_context[role])
        for role in ROLE_ORDER
    ):
        raise Invalid("authorization roster differs from authenticated authority context")
    expected_pairs = {
        (i, role)
        for i, operation in enumerate(intent["operations"])
        for role in operation["requiredRoles"]
    }
    seen: set[tuple[int, str]] = set()
    for authorization in authorizations:
        if not isinstance(authorization, dict):
            raise Invalid("authorization is not an object")
        if not _is_pure_json(authorization):
            raise Invalid("authorization is not NFC-normalized safe-integer JSON")
        validate_schema(
            authorization, "atomic-work-authorization-v1.schema.json"
        )
        index = authorization.get("operationIndex")
        if not isinstance(index, int) or isinstance(index, bool) or not (0 <= index < len(intent["operations"])):
            raise Invalid("invalid authorization operationIndex")
        operation = intent["operations"][index]
        role = authorization.get("role")
        expected = {
            "authorizationVersion": "1",
            "workId": derived,
            "executionProfile": intent["executionProfile"],
            "networkId": intent["networkId"],
            "railId": intent["railId"],
            "jobId": intent["jobId"],
            "phaseIndex": intent["phaseIndex"],
            "operationId": operation["operationId"],
            "operationIndex": index,
            "operationKind": operation["kind"],
            "role": role,
            "signer": roster.get(role),
        }
        if authorization.get("algorithm") != "ed25519":
            raise Invalid("authorization algorithm is not supported by verified capability")
        for field, value in expected.items():
            if field == "signer":
                if not claim_equal(authorization.get(field), value):
                    raise Invalid(f"authorization envelope mismatch: {field}")
                continue
            if type(authorization.get(field)) is not type(value) or authorization.get(field) != value:
                raise Invalid(f"authorization envelope mismatch: {field}")
        pair = (index, role)
        if pair not in expected_pairs or pair in seen:
            raise Invalid("unexpected or duplicate operation authorization")
        signer = claim_key(authorization.get("signer"))
        encoded_public = _public_key_for_claim(public_keys, signer)
        if encoded_public is None:
            raise Unknown("authorization key unavailable")
        digest = authorization_hash(authorization)
        if not ed25519_verify(
            _ed25519_public_bytes(encoded_public),
            AUTH_DOMAIN + digest.encode("ascii"),
            _ed25519_signature_bytes(authorization.get("value", "")),
        ):
            raise Invalid("invalid operation authorization signature")
        seen.add(pair)
    if seen != expected_pairs:
        raise Invalid("missing required operation authorization")


def _network_authority(data: dict[str, Any]) -> str:
    capability = data.get("capability")
    if not isinstance(capability, dict):
        raise Unknown("verified capability unavailable")
    verify_capability(capability, data["publicKeys"], data.get("expectedNetworkAuthority"))
    return claim_key(capability.get("networkAuthority"))


def _verify_ledger_evidence(
    evidence: dict[str, Any], public_keys: dict[str, str], expected_signer: str,
    expected_native_transaction_ref: dict[str, Any] | None,
    expected_proof_profile: str, expected_validator_set_id: str,
    expected_nonce: str | None = None, expected_fee: str | None = None,
) -> None:
    expected_fields = {
        "evidenceVersion", "attemptId", "workId", "nativeTransactionRef",
        "state", "blockId", "proofProfile", "validatorSetId", "nonce", "fee",
        "signature",
    }
    if (
        set(evidence) != expected_fields
        or evidence.get("evidenceVersion") != "test-1"
        or not isinstance(evidence.get("blockId"), str)
        or not evidence["blockId"]
    ):
        raise Invalid("synthetic attempt lifecycle evidence shape mismatch")
    verify_embedded(evidence, public_keys, _LEDGER_TEST_DOMAIN)
    require_signer(evidence, expected_signer)
    native_ref = evidence.get("nativeTransactionRef")
    if (
        not isinstance(native_ref, dict)
        or set(native_ref) != {"kind", "value"}
        or not all(
            isinstance(native_ref.get(field), str) and native_ref[field]
            for field in ("kind", "value")
        )
    ):
        raise Invalid("lifecycle evidence nativeTransactionRef malformed")
    if not isinstance(expected_native_transaction_ref, dict):
        raise Unknown("independently expected nativeTransactionRef unavailable")
    if native_ref != expected_native_transaction_ref:
        raise Invalid("lifecycle evidence nativeTransactionRef mismatch")
    if evidence.get("state") not in {
        "authoritative-non-inclusion", "included-committed", "included-rolled-back"
    }:
        raise Invalid("unsupported attempt lifecycle state")
    if (
        evidence.get("proofProfile") != expected_proof_profile
        or evidence.get("validatorSetId") != expected_validator_set_id
    ):
        raise Invalid("attempt lifecycle evidence proof-profile binding mismatch")
    if (
        not isinstance(evidence.get("nonce"), str)
        or not evidence["nonce"]
        or evidence.get("fee") != "1"
        or (expected_nonce is not None and evidence["nonce"] != expected_nonce)
        or (expected_fee is not None and evidence["fee"] != expected_fee)
    ):
        raise Invalid("attempt lifecycle evidence fee/nonce subject mismatch")


def evaluate_attempts(data: dict[str, Any]) -> dict[str, Any] | None:
    intent = data["intent"]
    validate_intent(intent)
    wid = work_id(intent)
    canonical = canonicalize(intent)
    network_authority = _network_authority(data)
    capability = data["capability"]
    proof_profile = capability["proofProfile"]
    validator_set_id = capability["validatorSetId"]
    attempts = data.get("attempts", [])
    by_id: dict[str, dict[str, Any]] = {}
    included: list[dict[str, Any]] = []
    native_refs: set[bytes] = set()
    for attempt in attempts:
        validate_schema(attempt, "atomic-work-attempt-v1.schema.json")
        if attempt.get("attemptVersion") != "1":
            raise Invalid("unsupported attemptVersion")
        native_ref = attempt.get("nativeTransactionRef")
        if (
            not isinstance(native_ref, dict)
            or set(native_ref) != {"kind", "value"}
            or not all(isinstance(native_ref.get(k), str) and native_ref[k] for k in ("kind", "value"))
        ):
            raise Invalid("attempt nativeTransactionRef malformed")
        native_ref_key = jcs_bytes(native_ref)
        if native_ref_key in native_refs:
            raise Invalid("duplicate nativeTransactionRef across Work attempts")
        native_refs.add(native_ref_key)
        auths = attempt.get("authorizations")
        if not isinstance(auths, list):
            raise Unknown("attempt authorizations unavailable")
        verify_authorizations(
            intent, auths, data["publicKeys"], data.get("authority"), data.get("capability"),
            data.get("expectedNetworkAuthority"), data.get("expectedProofProfile"),
            data.get("expectedRailRegistryAuthority"),
        )
        if attempt.get("workId") != wid or attempt.get("canonicalWorkBytes") != canonical:
            raise Invalid("attempt changes canonical Work bytes or workId")
        attempt_id = attempt.get("attemptId")
        if not isinstance(attempt_id, str) or attempt_id in by_id:
            raise Invalid("invalid or duplicate attemptId")
        by_id[attempt_id] = attempt
        evidence = attempt.get("lifecycleEvidence")
        if isinstance(evidence, dict):
            _verify_ledger_evidence(
                evidence, data["publicKeys"], network_authority, native_ref,
                proof_profile, validator_set_id,
                attempt.get("nonce"), attempt.get("fee"),
            )
            if evidence.get("attemptId") != attempt_id or evidence.get("workId") != wid:
                raise Invalid("attempt evidence tuple mismatch")
            if evidence["state"].startswith("included-"):
                if (
                    attempt.get("fee") != "1"
                    or not isinstance(attempt.get("nonce"), str)
                    or not attempt["nonce"]
                ):
                    raise Invalid("included attempt contradicts authenticated fixed-fee rule")
                included.append(attempt)
    for attempt in attempts:
        if attempt["attemptClass"] != "replacement":
            continue
        replaced = attempt["replacementFor"]
        prior = by_id.get(replaced)
        if prior is None:
            raise Invalid("replacement names an unknown attempt")
        proof = prior.get("lifecycleEvidence")
        if proof is None and prior.get("observation") in {"not-found", "timeout", "expired-local"}:
            raise Unknown("ordinary observation cannot authorize replacement")
        if not isinstance(proof, dict):
            raise Unknown("replacement authority unavailable")
        _verify_ledger_evidence(
            proof, data["publicKeys"], network_authority,
            prior.get("nativeTransactionRef"),
            proof_profile, validator_set_id,
            prior.get("nonce"), prior.get("fee"),
        )
        if proof.get("state") != "authoritative-non-inclusion":
            raise Invalid("included or unresolved attempt cannot be replaced")
    if len(included) > 1:
        raise Invalid("ledger selected more than one included attempt")
    winner = data.get("winningAttemptId")
    if included and winner != included[0]["attemptId"]:
        raise Invalid("winner does not match authenticated ledger")
    if not included and winner is not None:
        raise Invalid("winner claimed without inclusion evidence")
    effects = data.get("businessEffectAttempts", [])
    if any(effect != winner for effect in effects) or len(effects) > (1 if winner else 0):
        raise Invalid("late/competing attempt was not fenced")
    for attempt in attempts:
        attempt_class = attempt["attemptClass"]
        if attempt_class == "replay":
            replay_of = attempt["replayOf"]
            if winner is None:
                raise Invalid("exact replay has no authenticated winner")
            if replay_of != winner or attempt.get("returnedWinner") != winner:
                raise Invalid("exact replay did not return selected winner")
            if isinstance(attempt.get("lifecycleEvidence"), dict):
                raise Invalid("exact replay cannot claim a second ledger inclusion")
            if (
                "nonce" in attempt
                or attempt.get("fee") != "0"
                or attempt.get("replayEffects")
                != {"nonceConsumed": False, "feeCharged": "0"}
            ):
                raise Invalid("exact replay charged an additional fee or nonce")
        elif attempt_class in {"normal", "replacement"}:
            if (
                attempt.get("fee") != "1"
                or not isinstance(attempt.get("nonce"), str)
                or not attempt["nonce"]
            ):
                raise Invalid("normal/replacement attempt violates fixed-fee classification")
        else:  # The schema rejects this first; retain fail-closed locality.
            raise Invalid("unsupported attempt class")
    authenticated_winner = included[0] if included else None
    receipt = data.get("receipt")
    if isinstance(receipt, dict):
        verify_receipt(
            receipt, intent, data["publicKeys"], capability=data.get("capability"),
            purchase_intent=data.get("purchaseIntent"),
            purchase_receipt=data.get("purchaseReceipt"),
            expected_network_authority=data.get("expectedNetworkAuthority"),
            expected_proof_profile=data.get("expectedProofProfile"),
        )
        if authenticated_winner is None or receipt.get("winningAttempt") != {
            "attemptId": authenticated_winner["attemptId"],
            "nativeTransactionRef": authenticated_winner["nativeTransactionRef"],
        }:
            raise Invalid("receipt winner differs from authenticated ledger-selected attempt")
        expected_inclusion = {
            "committed": "included-committed",
            "rolled-back": "included-rolled-back",
        }.get(receipt.get("outcome"))
        if authenticated_winner["lifecycleEvidence"].get("state") != expected_inclusion:
            raise Invalid("receipt outcome differs from authenticated winner lifecycle state")
    return authenticated_winner


def _receipt_commitment(receipt: dict[str, Any]) -> str:
    core = copy.deepcopy({
        k: v for k, v in receipt.items()
        if k not in {"receiptCommitment", "finalityEvidence"}
    })
    core.get("blockRef", {}).pop("id", None)
    core.get("businessState", {}).pop("evidence", None)
    core.pop("slotStateEvidence", None)
    if core.get("profile") == "dacs-purchase-v1":
        slot_after = core.get("paymentSlot", {}).get("after", {})
        slot_after.pop("receiptCommitment", None)
        slot_after.pop("failureReceiptCommitment", None)
    return sha256_hex(WORK_RECEIPT_DOMAIN + jcs_bytes(core))


def _validated_storage_output(
    operation: dict[str, Any], result: dict[str, Any]
) -> dict[str, Any]:
    """Return the complete Demos storage result only after binding validation."""
    output = result.get("storageOutput")
    required = {"logicalAddress", "nativeAddress", "contentHash", "writer", "nonce"}
    if not isinstance(output, dict) or not required.issubset(output):
        raise Invalid("committed storage operation lacks complete storageOutput")
    if any(
        not isinstance(output.get(field), str) or not output[field]
        for field in ("logicalAddress", "nativeAddress", "writer", "nonce")
    ) or not isinstance(output.get("contentHash"), str) or not HEX_64.fullmatch(
        output["contentHash"]
    ):
        raise Invalid("committed storage operation has malformed storageOutput")
    payload = operation.get("payload", {})
    expected_content_hash = payload.get("contentHash")
    if expected_content_hash is None and isinstance(payload.get("artifact"), dict):
        expected_content_hash = sha256_hex(jcs_bytes(payload["artifact"]))
    if (
        output["logicalAddress"] != payload.get("logicalAddress")
        or output["contentHash"] != expected_content_hash
    ):
        raise Invalid("storageOutput contradicts the signed storage payload")
    return output


def verify_receipt(
    receipt: dict[str, Any], intent: dict[str, Any], public_keys: dict[str, str],
    *, capability: dict[str, Any] | None = None,
    purchase_intent: dict[str, Any] | None = None,
    purchase_receipt: dict[str, Any] | None = None,
    expected_network_authority: str | None = None,
    expected_proof_profile: str | None = None,
) -> None:
    if not _is_pure_json(receipt):
        raise Invalid("receipt is not NFC-normalized safe-integer JSON")
    validate_schema(receipt, "atomic-work-receipt-v1.schema.json")
    if not isinstance(capability, dict):
        raise Unknown("verified capability/proof profile unavailable")
    consume_capability_for_intent(
        intent, capability, public_keys, expected_network_authority,
        expected_proof_profile,
    )
    proof_profile = expected_proof_profile
    network_authority = claim_key(capability["networkAuthority"])
    if receipt.get("receiptVersion") != "1":
        raise Invalid("unsupported receipt version")
    block_timestamp = receipt.get("blockRef", {}).get("timestamp")
    if not isinstance(block_timestamp, int) or isinstance(block_timestamp, bool):
        raise Invalid("receipt block timestamp invalid")
    if block_timestamp >= intent.get("expiresAt", -1):
        raise Invalid("Work execution is expired at consensus transition")
    if receipt.get("workId") != work_id(intent):
        raise Invalid("receipt workId mismatch")
    for field in ("executionProfile", "profile", "networkId"):
        if receipt.get(field) != intent.get(field):
            raise Invalid(f"receipt {field} mismatch")
    results = receipt.get("operationResults")
    if not isinstance(results, list) or len(results) != len(intent["operations"]):
        raise Invalid("receipt operation count mismatch")
    for index, (operation, result) in enumerate(zip(intent["operations"], results)):
        if (
            result.get("operationId") != operation["operationId"]
            or result.get("operationIndex") != index
            or result.get("operationKind") != operation["kind"]
        ):
            raise Invalid("receipt operation order or identity mismatch")
        if result.get("inputHash") != sha256_hex(jcs_bytes(operation["payload"])):
            raise Invalid("operation receipt inputHash mismatch")
        if result.get("status") == "committed":
            if operation["kind"] == "storage-program-put":
                storage_output = _validated_storage_output(operation, result)
                expected_output = sha256_hex(jcs_bytes(storage_output))
            elif operation["kind"] == "native-dem-transfer":
                expected_output = sha256_hex(jcs_bytes(operation["payload"]))
            else:
                expected_output = sha256_hex(jcs_bytes({
                    "accepted": True, "operationId": operation["operationId"],
                }))
            if result.get("outputHash") != expected_output:
                raise Invalid("synthetic proof profile outputHash mismatch")
    if receipt.get("operationReceiptRoot") != operation_receipt_root(results):
        raise Invalid("operationReceiptRoot mismatch")
    business = receipt.get("businessState", {})
    witness_ref = business.get("evidence")
    if not isinstance(witness_ref, dict):
        raise Unknown("business-state witness unavailable")
    if witness_ref.get("kind") != "test-business-state-witness":
        raise Invalid("business-state evidence kind mismatch")
    try:
        witness = json.loads(b64u_decode(witness_ref.get("value", "")).decode("utf-8"))
    except (Invalid, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise Invalid("business-state witness encoding invalid") from exc
    if not isinstance(witness, dict):
        raise Invalid("business-state witness is not an object")
    verify_embedded(witness, public_keys, _STATE_TEST_DOMAIN)
    require_signer(witness, network_authority)
    pre_state, post_state = witness.get("preState"), witness.get("postState")
    if not isinstance(pre_state, dict) or not isinstance(post_state, dict):
        raise Invalid("invalid business-state witness")
    if business.get("preRoot") != state_root(pre_state) or business.get("postRoot") != state_root(post_state):
        raise Invalid("business-state root mismatch")
    if business.get("effectsRoot") != sha256_hex(jcs_bytes({"pre": pre_state, "post": post_state})):
        raise Invalid("synthetic proof profile effectsRoot mismatch")
    if (
        witness.get("proofProfile") != proof_profile
        or witness.get("validatorSetId") != capability["validatorSetId"]
    ):
        raise Invalid("business-state witness proof-profile binding mismatch")
    outcome = receipt.get("outcome")
    slot = receipt.get("paymentSlot")
    if not isinstance(slot, dict):
        raise Invalid("receipt paymentSlot transition missing")
    if intent["profile"] == "dacs-purchase-v1":
        slot_operations = [
            operation for operation in intent["operations"]
            if operation.get("kind") == "payment-slot-cas"
        ]
        if len(slot_operations) != 1:
            raise Invalid("Purchase Work does not carry exactly one signed payment slot")
        signed_slot_payload = slot_operations[0]["payload"]
        expected_slot_key = signed_slot_payload["slotKey"]
        if not _tuple_equal(expected_slot_key, intent):
            raise Invalid("Purchase signed slot key differs from top-level intent tuple")
    else:
        embedded = intent.get("operations", [{}])[0].get("payload", {}).get("receipt")
        if not isinstance(purchase_receipt, dict) or not isinstance(purchase_intent, dict):
            raise Unknown("verified Purchase intent and receipt unavailable for Completion")
        if not _json_equal(embedded, purchase_receipt):
            raise Invalid("Completion embedded receipt differs from verified Purchase receipt")
        if purchase_intent.get("profile") != "dacs-purchase-v1":
            raise Invalid("Completion prior Work is not a Purchase profile")
        for field in ("networkId", "railId", "jobId"):
            if purchase_intent.get(field) != intent.get(field):
                raise Invalid("Completion/Purchase tuple mismatch")
        verify_receipt(
            purchase_receipt, purchase_intent, public_keys, capability=capability,
            expected_network_authority=expected_network_authority,
            expected_proof_profile=expected_proof_profile,
        )
        payment = next((r for r in purchase_receipt.get("operationResults", []) if r.get("operationKind") == "native-dem-transfer"), None)
        if purchase_receipt.get("outcome") != "committed" or not isinstance(payment, dict) or payment.get("status") != "committed":
            raise Invalid("Completion prior Purchase lacks committed native transfer")
        expected_slot_key = purchase_receipt.get("paymentSlot", {}).get("key")
    if slot.get("key") != expected_slot_key:
        raise Invalid("receipt paymentSlot key does not match Work intent")
    if not isinstance(slot.get("before"), dict) or not isinstance(slot.get("after"), dict):
        raise Invalid("receipt paymentSlot before/after are not structured states")
    _generation(slot["before"].get("generation"), "receipt prior slot state")
    _generation(slot["after"].get("generation"), "receipt resulting slot state")
    terminal_generation: int | None = None
    if intent["profile"] == "dacs-purchase-v1":
        expected_before = signed_slot_payload["expected"]
        before_projection = {
            "state": slot["before"].get("state"),
            "generation": slot["before"].get("generation"),
        }
        if before_projection != expected_before:
            raise Invalid("Purchase receipt slot before-state contradicts signed CAS expectation")
        retry = expected_before["state"] == "rolled-back"
        terminal_generation = expected_before["generation"] + (1 if retry else 0)
        if retry and (
            slot["before"].get("failureReceiptCommitment")
            != intent.get("priorFailureReceiptCommitment")
            or slot["before"].get("conflictDigest")
            != signed_slot_payload["conflictDigest"]
            or not isinstance(slot["before"].get("workId"), str)
        ):
            raise Invalid("retry receipt is not bound to complete prior rolled-back state")
    slot_proof = verify_encoded_evidence(
        receipt.get("slotStateEvidence"), "test-payment-slot-state",
        public_keys, _SLOT_STATE_TEST_DOMAIN, expected_signer=network_authority,
    )
    expected_slot_subject = copy.deepcopy(slot)
    if intent["profile"] == "dacs-purchase-v1":
        expected_slot_subject["after"].pop("receiptCommitment", None)
        expected_slot_subject["after"].pop("failureReceiptCommitment", None)
    if (
        slot_proof.get("slot") != expected_slot_subject
        or slot_proof.get("networkId") != intent["networkId"]
        or slot_proof.get("workId") != receipt["workId"]
        or slot_proof.get("proofProfile") != proof_profile
        or slot_proof.get("validatorSetId") != capability["validatorSetId"]
    ):
        raise Invalid("slot-state proof subject mismatch")
    statuses = [result.get("status") for result in results]
    if outcome == "committed":
        if any(status != "committed" for status in statuses):
            raise Invalid("committed receipt has non-committed operation")
        if intent["profile"] == "dacs-purchase-v1":
            expected_after = {
                "state": "settled",
                "generation": terminal_generation,
                "workId": receipt["workId"],
                "conflictDigest": signed_slot_payload["conflictDigest"],
                "receiptCommitment": receipt.get("receiptCommitment"),
            }
            if slot["after"] != expected_after:
                raise Invalid("committed Purchase slot transition contradicts signed CAS payload")
        elif slot["before"] != slot["after"]:
            raise Invalid("Completion Work unexpectedly changed payment slot")
    elif outcome == "rolled-back":
        if pre_state != post_state:
            raise Invalid("rolled-back receipt changed business state")
        failed = receipt.get("failedOperationId")
        if failed not in [op["operationId"] for op in intent["operations"]]:
            raise Invalid("rolled-back receipt lacks failed operation")
        failed_index = [op["operationId"] for op in intent["operations"]].index(failed)
        for i, status in enumerate(statuses):
            wanted = "rolled-back" if i <= failed_index else "not-executed"
            if status != wanted:
                raise Invalid("rollback leaf status mismatch")
        for protected in witness.get("protectedKeys", []):
            if pre_state.get(protected, {"absent": True}) != post_state.get(protected, {"absent": True}):
                raise Invalid("rollback output changed or non-membership contradicted")
        if intent["profile"] == "dacs-purchase-v1":
            expected_after = {
                "state": "rolled-back",
                "generation": terminal_generation,
                "workId": receipt["workId"],
                "conflictDigest": signed_slot_payload["conflictDigest"],
                "failureReceiptCommitment": receipt.get("receiptCommitment"),
            }
            if slot["after"] != expected_after:
                raise Invalid("rolled-back Purchase slot transition contradicts signed CAS payload")
        elif slot["before"] != slot["after"]:
            raise Invalid("rolled-back Completion changed Purchase slot metadata")
    else:
        raise Invalid("invalid receipt outcome")
    envelope = receipt.get("envelopeEffects")
    if (
        not isinstance(envelope, dict)
        or envelope.get("nonceConsumed") is not True
        or envelope.get("feeCharged") != "1"
        or capability.get("limits", {}).get("feeRule") != "test-fixed-fee"
    ):
        raise Invalid("receipt envelope effects contradict authenticated fee rule")
    evidence = receipt.get("finalityEvidence")
    if receipt.get("receiptCommitment") != _receipt_commitment(receipt):
        raise Invalid("receiptCommitment does not match canonical receipt core")
    checkpoint = verify_encoded_evidence(
        evidence, "test-bft-checkpoint", public_keys, _CHECKPOINT_TEST_DOMAIN,
        expected_signer=network_authority,
    )
    if (
        checkpoint.get("networkId") != receipt.get("networkId")
        or checkpoint.get("blockId") != receipt.get("blockRef", {}).get("id")
        or checkpoint.get("receiptCommitment") != receipt.get("receiptCommitment")
        or checkpoint.get("proofProfile") != proof_profile
        or checkpoint.get("validatorSetId") != capability.get("validatorSetId")
    ):
        raise Invalid("finality checkpoint does not bind receipt")


def evaluate_receipt(data: dict[str, Any]) -> None:
    if data.get("receiptAvailability") == "unavailable":
        raise Unknown("receipt service unavailable; consensus reconstruction not supplied")
    verify_receipt(
        data["receipt"], data["intent"], data["publicKeys"],
        capability=data.get("capability"), purchase_intent=data.get("purchaseIntent"),
        purchase_receipt=data.get("purchaseReceipt"),
        expected_network_authority=data.get("expectedNetworkAuthority"),
        expected_proof_profile=data.get("expectedProofProfile"),
    )
    if data.get("authorizesResubmission") is True:
        raise Invalid("receipt/fee/nonce state cannot authorize resubmission")
    if data.get("claimsOtherAttemptAbsent") is True and data["receipt"].get("outcome") == "rolled-back":
        raise Invalid("included rollback does not prove other-attempt absence")


def evaluate_lifecycle(data: dict[str, Any]) -> None:
    evidence = data.get("evidence")
    if not isinstance(evidence, dict):
        raise Unknown("lifecycle/non-inclusion evidence unavailable")
    _verify_ledger_evidence(
        evidence, data["publicKeys"], _network_authority(data),
        data.get("nativeTransactionRef"),
        data["capability"]["proofProfile"],
        data["capability"]["validatorSetId"],
        data.get("expectedNonce"), data.get("expectedFee"),
    )
    if evidence.get("attemptId") != data.get("attemptId"):
        raise Invalid("lifecycle evidence attempt mismatch")
    if data.get("claimedState") != evidence.get("state"):
        raise Invalid("claimed lifecycle state contradicts evidence")


def evaluate_recovery(data: dict[str, Any]) -> None:
    boundary = data.get("crashBoundary")
    if boundary == "before-durable-admission":
        if data.get("inferredAbsent"):
            raise Invalid("crash before admission does not prove absence")
    elif boundary == "during-overlay":
        if data.get("preState") != data.get("postRecoveryState"):
            raise Invalid("overlay crash leaked a business effect")
    elif boundary == "after-consensus-commit":
        if data.get("recoveredReceiptHash") != data.get("committedReceiptHash"):
            raise Invalid("recovery changed committed receipt")
        if data.get("recoveredWinner") != data.get("committedWinner"):
            raise Invalid("recovery changed winner")
    else:
        raise Invalid("unknown crash boundary")


def evaluate_projection(data: dict[str, Any]) -> None:
    receipt = data["receipt"]
    intent = data["intent"]
    verify_receipt(
        receipt, intent, data["publicKeys"], capability=data.get("capability"),
        purchase_intent=data.get("purchaseIntent"), purchase_receipt=data.get("purchaseReceipt"),
        expected_network_authority=data.get("expectedNetworkAuthority"),
        expected_proof_profile=data.get("expectedProofProfile"),
    )
    evidence = data.get("operationEvidence")
    if not isinstance(evidence, dict):
        raise Unknown("operation inclusion evidence unavailable")
    leaf = evidence.get("leaf")
    if not isinstance(leaf, dict) or not verify_inclusion(
        leaf, evidence.get("inclusionPath", []), receipt["operationReceiptRoot"]
    ):
        raise Invalid("operation leaf inclusion proof invalid")
    operation_index = leaf.get("operationIndex")
    if (
        not isinstance(operation_index, int)
        or isinstance(operation_index, bool)
        or not (0 <= operation_index < len(intent["operations"]))
        or receipt["operationResults"][operation_index] != leaf
        or leaf.get("status") != "committed"
        or leaf.get("operationKind") != "storage-program-put"
    ):
        raise Invalid("projection leaf is not the committed receipt storage result")
    anchor = data.get("anchorReceipt", {})
    storage = _validated_storage_output(intent["operations"][operation_index], leaf)
    required_anchor_fields = {
        "receiptVersion", "substrate", "finalityProfile", "logicalAddress",
        "nativeAddress", "contentHash", "transactionRef", "writer", "nonce",
        "state", "observationDisposition", "observedAt", "blockRef", "evidence",
    }
    if not isinstance(anchor, dict) or set(anchor) != required_anchor_fields:
        raise Invalid("projection is not the complete finalized CORE AnchorReceipt shape")
    for field in ("logicalAddress", "nativeAddress", "contentHash", "writer", "nonce"):
        if anchor.get(field) != storage.get(field):
            raise Invalid(f"projection changed {field}")
    if (
        anchor.get("receiptVersion") != "1"
        or anchor.get("substrate") != receipt.get("networkId")
        or anchor.get("finalityProfile") != data.get("expectedProofProfile")
        or anchor.get("state") != "finalized"
        or anchor.get("observationDisposition") != "established"
        or anchor.get("blockRef") != receipt.get("blockRef")
        or not isinstance(anchor.get("observedAt"), int)
        or isinstance(anchor.get("observedAt"), bool)
        or anchor["observedAt"] < receipt.get("blockRef", {}).get("timestamp", 0)
    ):
        raise Invalid("projection changed receipt finality/lifecycle context")
    transaction_ref = anchor.get("transactionRef", {})
    expected_value = f"{receipt['workId']}/{leaf['operationId']}"
    if transaction_ref != {
        "kind": "demos-work-operation-v1", "value": expected_value
    }:
        raise Invalid("projection operation reference mismatch")
    anchor_evidence = anchor.get("evidence")
    if not isinstance(anchor_evidence, dict):
        raise Unknown("projected receipt does not resolve Work evidence")
    if anchor_evidence.get("kind") != "demos-work-operation-proof-v1":
        raise Invalid("projected receipt evidence kind mismatch")
    try:
        resolved = json.loads(b64u_decode(anchor_evidence.get("value", "")).decode("utf-8"))
    except (Invalid, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise Invalid("projected receipt evidence encoding invalid") from exc
    expected_operation_ref = {
        "kind": "demos-work-operation-v1",
        "networkId": receipt["networkId"],
        "workId": receipt["workId"],
        "operationIndex": operation_index,
        "operationId": leaf["operationId"],
        "operationKind": leaf["operationKind"],
    }
    if (
        not isinstance(resolved, dict)
        or set(resolved) != {
            "operationRef", "receiptContentHash", "leaf", "inclusionPath",
            "finalityEvidence",
        }
        or resolved.get("operationRef") != expected_operation_ref
        or resolved.get("receiptContentHash") != receipt_hash(receipt)
        or resolved.get("leaf") != leaf
        or resolved.get("inclusionPath") != evidence.get("inclusionPath", [])
        or resolved.get("finalityEvidence") != receipt.get("finalityEvidence")
    ):
        raise Invalid("projected receipt evidence does not resolve verified Work proof")


def _verify_artifact(artifact: dict[str, Any], public_keys: dict[str, str]) -> None:
    verify_embedded(artifact, public_keys, _ARTIFACT_TEST_DOMAIN)
    disclosed = artifact.get("contentHash")
    body = artifact.get("body")
    if disclosed != sha256_hex(jcs_bytes(body)):
        raise Invalid("artifact contentHash mismatch")


def _verify_rail_definition(
    rail: dict[str, Any], public_keys: dict[str, str], steward: str,
) -> None:
    """Verify the closed native-DEM RailDefinition used by this candidate."""
    if not _is_pure_json(rail):
        raise Invalid("RailDefinition is not NFC-normalized safe-integer JSON")
    if set(rail) != {
        "railVersion", "railId", "railType", "asset", "network",
        "phaseHandler", "parameters", "availability", "governance",
        "signature",
    }:
        raise Invalid("RailDefinition is not the closed candidate shape")
    rail_id = rail.get("railId")
    if (
        type(rail.get("railVersion")) is not int
        or not (1 <= rail["railVersion"] <= SAFE_INT_MAX)
        or not isinstance(rail_id, str)
        or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._:-]{0,63}", rail_id)
        or rail.get("railType") != "demos-native"
        or rail.get("asset") != {
            "kind": "native-dem", "symbol": "DEM", "decimals": 9,
        }
        or rail.get("network") != {"kind": "demos"}
        or rail.get("phaseHandler") != "pay-dem"
        or rail.get("parameters") != {}
        or rail.get("availability") != "live"
    ):
        raise Invalid("native-DEM RailDefinition violates RD-3/RD-5/RD-6/RAV-1")
    governance = rail.get("governance")
    governance_fields = {"proposedBy", "acceptedAt", "anchoring"}
    if type(rail.get("railVersion")) is int and rail["railVersion"] > 1:
        governance_fields.add("supersedes")
    if (
        not isinstance(governance, dict)
        or set(governance) != governance_fields
        or not claim_equal(governance.get("proposedBy"), steward)
        or type(governance.get("acceptedAt")) is not int
        or not (0 <= governance["acceptedAt"] <= SAFE_INT_MAX)
        or governance.get("anchoring") != "single-signer"
        or (
            rail["railVersion"] > 1
            and (
                type(governance.get("supersedes")) is not int
                or not (1 <= governance["supersedes"] < rail["railVersion"])
            )
        )
    ):
        raise Invalid("RailDefinition governance does not bind the pinned steward")
    signature = rail.get("signature")
    if not isinstance(signature, dict) or set(signature) != {
        "algorithm", "signer", "value",
    }:
        raise Invalid("RailDefinition signature envelope is malformed")
    verify_embedded(rail, public_keys, _RAIL_DOMAIN)
    require_signer(rail, steward)


def _verify_rail_registry_resolution(
    authority: dict[str, Any], rail: dict[str, Any], *,
    public_keys: dict[str, str], network_authority: str,
    network_id: str, proof_profile: str, validator_set_id: str,
    registry_version: int, rail_ref: dict[str, Any],
    session_started_at: int,
) -> None:
    index = authority.get("railRegistryIndex")
    index_receipt = authority.get("railRegistryIndexReceipt")
    rail_receipt = authority.get("railDefinitionReceipt")
    if not all(isinstance(value, dict) for value in (
        index, index_receipt, rail_receipt,
    )):
        raise Unknown("finalized rail-registry index/definition resolution unavailable")
    if (
        set(index) != {"registryVersion", "logicalAddress", "entries"}
        or index.get("registryVersion") != registry_version
        or index.get("logicalAddress") != "dacs4:registry:v0.1"
        or not isinstance(index.get("entries"), list)
    ):
        raise Invalid("rail-registry index snapshot is malformed or unpinned")
    entries = index["entries"]
    matching = [
        entry for entry in entries
        if isinstance(entry, dict) and entry.get("railId") == rail.get("railId")
    ]
    if len(matching) != 1:
        raise Invalid("selected rail is absent or duplicated in the pinned registry")
    entry = matching[0]
    if (
        set(entry) != {"railId", "latestVersion", "versions"}
        or type(entry.get("latestVersion")) is not int
        or not (1 <= entry["latestVersion"] <= SAFE_INT_MAX)
        or not isinstance(entry.get("versions"), list)
    ):
        raise Invalid("rail-registry entry version selection is inconsistent")
    allowed_rail_ref_fields = {"railId", "railVersion", "parameters"}
    if (
        not isinstance(rail_ref, dict)
        or "railId" not in rail_ref
        or not set(rail_ref).issubset(allowed_rail_ref_fields)
        or rail_ref.get("railId") != rail.get("railId")
        or (
            "parameters" in rail_ref
            and (
                not isinstance(rail_ref["parameters"], dict)
                or not _is_pure_json(rail_ref["parameters"])
            )
        )
    ):
        raise Invalid("Agreement rail reference does not select this definition")
    pinned_version = rail_ref.get("railVersion")
    selected_version = (
        entry["latestVersion"] if pinned_version is None else pinned_version
    )
    if (
        type(selected_version) is not int
        or not (1 <= selected_version <= SAFE_INT_MAX)
        or rail.get("railVersion") != selected_version
    ):
        raise Invalid("rail definition does not match the Agreement-selected version")
    versions = [
        version for version in entry["versions"]
        if isinstance(version, dict)
        and version.get("railVersion") == rail.get("railVersion")
    ]
    if len(versions) != 1 or set(versions[0]) != {
        "railVersion", "logicalAddress", "contentHash",
    }:
        raise Invalid("selected rail version is not uniquely indexed")
    selected = versions[0]
    expected_address = (
        f"dacs4:rail:{cf4_encode(rail['railId'])}:{rail['railVersion']}"
    )
    if selected.get("logicalAddress") != expected_address:
        raise Invalid("registry selected a non-canonical rail definition address")
    rail_hash = sha256_hex(jcs_bytes(rail))
    if selected.get("contentHash") != rail_hash:
        raise Invalid("pinned registry rail content hash mismatch")
    _verify_anchor_receipt(
        index_receipt, logical="dacs4:registry:v0.1",
        content_hash=sha256_hex(jcs_bytes(index)), public_keys=public_keys,
        network_authority=network_authority, network_id=network_id,
        proof_profile=proof_profile, validator_set_id=validator_set_id,
    )
    _verify_anchor_receipt(
        rail_receipt, logical=selected.get("logicalAddress"),
        content_hash=rail_hash, public_keys=public_keys,
        network_authority=network_authority, network_id=network_id,
        proof_profile=proof_profile, validator_set_id=validator_set_id,
    )
    accepted_at = rail.get("governance", {}).get("acceptedAt")
    receipt_times = (
        index_receipt.get("blockRef", {}).get("timestamp"),
        rail_receipt.get("blockRef", {}).get("timestamp"),
    )
    if (
        type(session_started_at) is not int
        or type(accepted_at) is not int
        or accepted_at > session_started_at
        or any(type(value) is not int or value > session_started_at for value in receipt_times)
    ):
        raise Invalid("rail definition was not accepted and pinned by session start")


def _identity_bundle_hash(bundle: dict[str, Any]) -> str:
    return sha256_hex(jcs_bytes({k: v for k, v in bundle.items() if k != "presentation"}))


def _verify_identity_bundle(bundle: dict[str, Any], public_keys: dict[str, str]) -> None:
    if bundle.get("bundleVersion") != "1" or not isinstance(bundle.get("claims"), list):
        raise Invalid("pinned payer IdentityBundle malformed")
    presented = claim_key(bundle.get("presentedBy"))
    refs = [claim_key(c.get("ref")) for c in bundle["claims"] if isinstance(c, dict)]
    if not any(claim_equal(presented, ref) for ref in refs):
        raise Invalid("IdentityBundle presentedBy missing from claims")
    presentation = bundle.get("presentation", {})
    if presentation.get("kind") != "per-claim":
        raise Invalid("synthetic profile requires per-claim IdentityBundle proof")
    message = b"dacs-bundle-presentation:v1:" + _identity_bundle_hash(bundle).encode("ascii")
    signatures = presentation.get("signatures", [])
    match = next((
        s for s in signatures
        if isinstance(s, dict) and claim_equal(s.get("ref"), presented)
    ), None)
    key = _public_key_for_claim(public_keys, presented)
    if not isinstance(match, dict) or key is None:
        raise Unknown("payer IdentityBundle presentation key unavailable")
    if not ed25519_verify(
        _ed25519_public_bytes(key), message,
        _ed25519_signature_bytes(match.get("signature", "")),
    ):
        raise Invalid("payer IdentityBundle presentation signature invalid")


def _bundle_native_account(
    bundle: dict[str, Any], claim: str, account_role: str,
) -> str:
    """Resolve one authenticated native-account mapping without caller inference."""
    matches = [
        candidate for candidate in bundle.get("claims", [])
        if isinstance(candidate, dict) and claim_equal(candidate.get("ref"), claim)
    ]
    if len(matches) != 1:
        raise Unknown(
            f"unique authenticated {account_role} native-account claim unavailable"
        )
    account = matches[0].get("metadata", {}).get("nativeAccount")
    if not isinstance(account, str) or not account:
        raise Unknown(f"authenticated {account_role} native account unavailable")
    return account


def _agreement_hash(agreement: dict[str, Any]) -> str:
    return sha256_hex(jcs_bytes({k: v for k, v in agreement.items() if k != "signatures"}))


def _agreement_artifact_kind(agreement: dict[str, Any]) -> str:
    """Select exactly one DACS-3 agreement artifact before reading its terms."""
    legacy = (
        agreement.get("agreementVersion") == "1"
        and "payeeBoundAgreementVersion" not in agreement
    )
    payee_bound = (
        agreement.get("payeeBoundAgreementVersion") == "1"
        and "agreementVersion" not in agreement
    )
    if legacy == payee_bound:
        raise Invalid("agreement artifact must carry exactly one supported discriminator")
    terms = agreement.get("terms")
    if not isinstance(terms, dict):
        raise Invalid("agreement terms are unavailable")
    if legacy:
        if "payoutBindings" in terms:
            raise Invalid("legacy AgreementDocument cannot carry payout bindings")
        return "legacy"
    if not isinstance(terms.get("payoutBindings"), list):
        raise Invalid("PayeeBoundAgreementDocument payout bindings are unavailable")
    return "payee-bound"


def _verify_agreement(
    agreement: dict[str, Any], public_keys: dict[str, str]
) -> str:
    if not _is_pure_json(agreement):
        raise Invalid("AgreementArtifact is not NFC-normalized safe-integer JSON")
    artifact_kind = _agreement_artifact_kind(agreement)
    parties = agreement.get("parties")
    if not isinstance(parties, list):
        raise Invalid("AgreementArtifact parties missing")
    party_map = {p.get("role"): p for p in parties if isinstance(p, dict)}
    if set(party_map) != {"buyer", "seller"}:
        raise Invalid("AgreementArtifact buyer/seller authority missing")
    if any(
        not _valid_attestation_ref(party_map[role].get("vetRecordRef"))
        for role in ("buyer", "seller")
    ):
        raise Invalid("AgreementParty vetRecordRef is missing or malformed")
    digest = _agreement_hash(agreement)
    sigs = agreement.get("signatures")
    if not isinstance(sigs, list):
        raise Unknown("AgreementArtifact signatures unavailable")
    signature_domain = (
        _AGREEMENT_DOMAIN
        if artifact_kind == "legacy"
        else _PAYEE_BOUND_AGREEMENT_DOMAIN
    )
    for role in ("buyer", "seller"):
        signer = claim_key(party_map[role].get("primaryClaim"))
        sig = next((
            candidate for candidate in sigs
            if isinstance(candidate, dict)
            and claim_equal(candidate.get("party"), signer)
        ), None)
        key = _public_key_for_claim(public_keys, signer)
        if not isinstance(sig, dict) or key is None:
            raise Unknown("required AgreementSignature unavailable")
        if sig.get("algorithm") != "ed25519" or not ed25519_verify(
            _ed25519_public_bytes(key), signature_domain + digest.encode("ascii"),
            _ed25519_signature_bytes(sig.get("value", "")),
        ):
            raise Invalid("AgreementSignature invalid")
    return artifact_kind


def _verify_anchor_receipt(
    receipt: dict[str, Any], *, logical: str, content_hash: str,
    public_keys: dict[str, str], network_authority: str,
    network_id: str, proof_profile: str, validator_set_id: str,
) -> None:
    required = {
        "receiptVersion": "1", "logicalAddress": logical,
        "contentHash": content_hash, "state": "finalized",
        "observationDisposition": "established",
    }
    if any(receipt.get(k) != v for k, v in required.items()):
        raise Invalid("AnchorReceipt does not establish finalized artifact binding")
    for key in (
        "substrate", "finalityProfile", "nativeAddress", "transactionRef",
        "writer", "nonce", "observedAt", "blockRef", "evidence",
    ):
        if key not in receipt:
            raise Invalid(f"AnchorReceipt missing {key}")
    if (
        receipt.get("substrate") != network_id
        or receipt.get("finalityProfile") != proof_profile
        or not isinstance(receipt.get("nativeAddress"), str)
        or not receipt["nativeAddress"]
        or not isinstance(receipt.get("writer"), str)
        or not receipt["writer"]
        or not isinstance(receipt.get("nonce"), str)
        or not receipt["nonce"]
        or not isinstance(receipt.get("transactionRef"), dict)
        or set(receipt["transactionRef"]) != {"kind", "value"}
        or not all(
            isinstance(receipt["transactionRef"].get(field), str)
            and receipt["transactionRef"][field]
            for field in ("kind", "value")
        )
        or not isinstance(receipt.get("observedAt"), int)
        or isinstance(receipt.get("observedAt"), bool)
        or not (0 <= receipt["observedAt"] <= SAFE_INT_MAX)
        or not isinstance(receipt.get("blockRef"), dict)
        or not isinstance(receipt["blockRef"].get("id"), str)
        or not receipt["blockRef"]["id"]
        or not isinstance(receipt["blockRef"].get("timestamp"), int)
        or isinstance(receipt["blockRef"].get("timestamp"), bool)
        or not (0 <= receipt["blockRef"]["timestamp"] <= SAFE_INT_MAX)
    ):
        raise Invalid("AnchorReceipt network/finality subject is malformed")
    proof = verify_encoded_evidence(
        receipt.get("evidence"), "test-anchor-finality", public_keys,
        _ANCHOR_TEST_DOMAIN, expected_signer=network_authority,
    )
    expected = {
        "logicalAddress": logical,
        "nativeAddress": receipt.get("nativeAddress"),
        "contentHash": content_hash,
        "transactionRef": receipt.get("transactionRef"),
        "writer": receipt.get("writer"),
        "nonce": receipt.get("nonce"),
        "state": "finalized",
        "blockRef": receipt.get("blockRef"),
        "networkId": network_id,
        "proofProfile": proof_profile,
        "validatorSetId": validator_set_id,
    }
    if set(proof) != set(expected) | {"signature"}:
        raise Invalid("AnchorReceipt finality proof subject is not the closed test shape")
    if any(proof.get(field) != value for field, value in expected.items()):
        raise Invalid("AnchorReceipt finality proof subject mismatch")


