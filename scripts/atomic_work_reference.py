#!/usr/bin/env python3
"""Small, dependency-free reference model for Atomic DACS Work candidate vectors.

This is deliberately a verifier, not a runtime implementation.  It models the
pure-data identity, authorization, dependency, attempt/winner, receipt,
payment-slot, settlement-evidence, and role-anchoring predicates exercised by
the candidate vectors generated by :mod:`generate_atomic_work_vectors`.

The Ed25519 routines are the compact RFC 8032 reference equations.  They exist
here so a clean checkout can verify the fixed public test signatures without a
native crypto package.  They MUST NOT be used as production cryptography.
"""

