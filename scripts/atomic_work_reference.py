class Invalid(ValueError):
    """The supplied authenticated data contradicts a normative predicate."""


class Unknown(RuntimeError):
    """The evidence needed for a safety decision is unavailable."""


class Malformed(ValueError):
    """Non-canonical wire data for which DACS specifies an ``error`` verdict."""


def jcs_bytes(value: Any) -> bytes:
    return canonicalize(value).encode("utf-8")


def sha256(raw: bytes) -> bytes:
    return hashlib.sha256(raw).digest()


def sha256_hex(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def b64u(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


def b64u_decode(value: str) -> bytes:
    if (
        not isinstance(value, str)
        or not re.fullmatch(r"[A-Za-z0-9_-]*", value)
        or len(value) % 4 == 1
    ):
        raise Invalid("base64url value must be an unpadded string")
    try:
        decoded = base64.b64decode(
            value.encode("ascii") + b"=" * (-len(value) % 4),
            altchars=b"-_", validate=True,
        )
    except (ValueError, UnicodeEncodeError) as exc:
        raise Invalid("invalid base64url value") from exc
    if b64u(decoded) != value:
        raise Invalid("non-canonical base64url encoding")
    return decoded


def _ed25519_public_bytes(value: Any) -> bytes:
    raw = b64u_decode(value)
    if len(raw) != 32:
        raise Invalid("Ed25519 public key must be exactly 32 bytes")
    return raw


def _ed25519_signature_bytes(value: Any) -> bytes:
    raw = b64u_decode(value)
    if len(raw) != 64:
        raise Invalid("Ed25519 signature must be exactly 64 bytes")
    return raw


# ---- dependency-free Ed25519 (RFC 8032 reference equations) -----------------

_Q = 2**255 - 19
_L = 2**252 + 27742317777372353535851937790883648493
_D = (-121665 * pow(121666, _Q - 2, _Q)) % _Q
_I = pow(2, (_Q - 1) // 4, _Q)


def _xrecover(y: int) -> int:
    xx = (y * y - 1) * pow(_D * y * y + 1, _Q - 2, _Q)
    x = pow(xx, (_Q + 3) // 8, _Q)
    if (x * x - xx) % _Q != 0:
        x = (x * _I) % _Q
    if x & 1:
        x = _Q - x
    return x


_BY = (4 * pow(5, _Q - 2, _Q)) % _Q
_BX = _xrecover(_BY)
_B = (_BX, _BY, 1, (_BX * _BY) % _Q)
_IDENTITY = (0, 1, 1, 0)


def _edwards(
    p: tuple[int, int, int, int], q: tuple[int, int, int, int]
) -> tuple[int, int, int, int]:
    """Complete extended-coordinate addition for a=-1 Edwards25519."""
    x1, y1, z1, t1 = p
    x2, y2, z2, t2 = q
    a = ((y1 - x1) * (y2 - x2)) % _Q
    b = ((y1 + x1) * (y2 + x2)) % _Q
    c = (2 * _D * t1 * t2) % _Q
    d = (2 * z1 * z2) % _Q
    e = (b - a) % _Q
    f = (d - c) % _Q
    g = (d + c) % _Q
    h = (b + a) % _Q
    return (e * f % _Q, g * h % _Q, f * g % _Q, e * h % _Q)


def _edwards_double(p: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    x, y, z, _ = p
    a = x * x % _Q
    b = y * y % _Q
    c = 2 * z * z % _Q
    d = (-a) % _Q
    e = ((x + y) * (x + y) - a - b) % _Q
    g = (d + b) % _Q
    f = (g - c) % _Q
    h = (d - b) % _Q
    return (e * f % _Q, g * h % _Q, f * g % _Q, e * h % _Q)


def _scalarmult(
    p: tuple[int, int, int, int], scalar: int
) -> tuple[int, int, int, int]:
    result = _IDENTITY
    addend = p
    while scalar:
        if scalar & 1:
            result = _edwards(result, addend)
        addend = _edwards_double(addend)
        scalar >>= 1
    return result


def _encode_point(p: tuple[int, int, int, int]) -> bytes:
    x, y, z, _ = p
    z_inv = pow(z, _Q - 2, _Q)
    x = x * z_inv % _Q
    y = y * z_inv % _Q
    return int.to_bytes(y | ((x & 1) << 255), 32, "little")


def _decode_point(encoded: bytes) -> tuple[int, int, int, int]:
    if len(encoded) != 32:
        raise Invalid("Ed25519 point is not 32 bytes")
    value = int.from_bytes(encoded, "little")
    y = value & ((1 << 255) - 1)
    if y >= _Q:
        raise Invalid("non-canonical Ed25519 point")
    x = _xrecover(y)
    if (x & 1) != (value >> 255):
        x = _Q - x
    p = (x, y, 1, x * y % _Q)
    if _encode_point(p) != encoded:
        raise Invalid("non-canonical Ed25519 encoding")
    return p


def _secret_scalar(seed: bytes) -> tuple[int, bytes]:
    if len(seed) != 32:
        raise ValueError("Ed25519 seed must be 32 bytes")
    digest = hashlib.sha512(seed).digest()
    scalar_bytes = bytearray(digest[:32])
    scalar_bytes[0] &= 248
    scalar_bytes[31] &= 63
    scalar_bytes[31] |= 64
    return int.from_bytes(scalar_bytes, "little"), digest[32:]


def ed25519_public_key(seed: bytes) -> bytes:
    scalar, _ = _secret_scalar(seed)
    return _encode_point(_scalarmult(_B, scalar))


def ed25519_sign(seed: bytes, message: bytes) -> bytes:
    scalar, prefix = _secret_scalar(seed)
    public = ed25519_public_key(seed)
    r = int.from_bytes(hashlib.sha512(prefix + message).digest(), "little") % _L
    encoded_r = _encode_point(_scalarmult(_B, r))
    challenge = int.from_bytes(
        hashlib.sha512(encoded_r + public + message).digest(), "little"
    ) % _L
    s = (r + challenge * scalar) % _L
    return encoded_r + int.to_bytes(s, 32, "little")


def ed25519_verify(public: bytes, message: bytes, signature: bytes) -> bool:
    if len(public) != 32 or len(signature) != 64:
        return False
    encoded_r, encoded_s = signature[:32], signature[32:]
    s = int.from_bytes(encoded_s, "little")
    if s >= _L:
        return False
    try:
        a = _decode_point(public)
        r = _decode_point(encoded_r)
    except Invalid:
        return False
    challenge = int.from_bytes(
        hashlib.sha512(encoded_r + public + message).digest(), "little"
    ) % _L
    # Cofactor multiplication rejects small-order malleability while retaining
    # the compact affine reference implementation.
    left = _scalarmult(_B, (s * 8) % _L)
    right = _scalarmult(_edwards(r, _scalarmult(a, challenge)), 8)
    return (
        left[0] * right[2] % _Q == right[0] * left[2] % _Q
        and left[1] * right[2] % _Q == right[1] * left[2] % _Q
    )


def claim_key(claim: Any) -> str:
    if (
        isinstance(claim, str)
        and CLAIM_REFERENCE.fullmatch(claim)
        and claim.split(":", 1)[0] == claim.split(":", 1)[0].lower()
    ):
        return claim
    raise Invalid("signer is not a canonical ClaimReference string")


def require_signer(value: dict[str, Any], expected: str, field: str = "signature") -> None:
    """Require a verified embedded object to name its authenticated authority."""
    if claim_key(value.get(field, {}).get("signer")) != claim_key(expected):
        raise Invalid(f"{field} signer is not the authenticated authority")


def _signed_hash(value: dict[str, Any], excluded: Iterable[str]) -> str:
    unsigned = {k: v for k, v in value.items() if k not in set(excluded)}
    return sha256_hex(jcs_bytes(unsigned))


def sign_embedded(
    value: dict[str, Any], signer: str, seed: bytes, domain: bytes,
    *, field: str = "signature", excluded: Iterable[str] | None = None,
) -> dict[str, Any]:
    """Return a copy carrying a deterministic signature over its unsigned hash."""
    out = copy.deepcopy(value)
    excluded_fields = tuple(excluded or (field,))
    digest = _signed_hash(out, excluded_fields)
    out[field] = {
        "algorithm": "ed25519",
        "signer": signer,
        "value": b64u(ed25519_sign(seed, domain + digest.encode("ascii"))),
    }
    return out


def verify_embedded(
    value: dict[str, Any], public_keys: dict[str, str], domain: bytes,
    *, field: str = "signature", excluded: Iterable[str] | None = None,
) -> None:
    sig = value.get(field)
    if not isinstance(sig, dict):
        raise Unknown(f"missing {field}")
    if sig.get("algorithm") != "ed25519":
        raise Invalid("unsupported signature algorithm")
    signer = claim_key(sig.get("signer"))
    encoded_public = public_keys.get(signer)
    if encoded_public is None:
        raise Unknown(f"no authenticated key for {signer}")
    excluded_fields = tuple(excluded or (field,))
    digest = _signed_hash(value, excluded_fields)
    message = domain + digest.encode("ascii")
    if not ed25519_verify(
        _ed25519_public_bytes(encoded_public), message,
        _ed25519_signature_bytes(sig.get("value", "")),
    ):
        raise Invalid(f"invalid {field}")


def verify_encoded_evidence(
    evidence: dict[str, Any], expected_kind: str,
    public_keys: dict[str, str], domain: bytes, *, expected_signer: str | None = None,
) -> dict[str, Any]:
    """Resolve a normative ``{kind,value}`` evidence reference and verify it."""
    if not isinstance(evidence, dict):
        raise Unknown(f"missing {expected_kind} evidence")
    if evidence.get("kind") != expected_kind:
        raise Invalid(f"unexpected evidence kind {evidence.get('kind')!r}")
    try:
        decoded = json.loads(b64u_decode(evidence.get("value", "")).decode("utf-8"))
    except (Invalid, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise Invalid(f"invalid encoded {expected_kind} evidence") from exc
    if not isinstance(decoded, dict):
        raise Invalid(f"decoded {expected_kind} evidence is not an object")
    verify_embedded(decoded, public_keys, domain)
    if expected_signer is not None:
        require_signer(decoded, expected_signer)
    return decoded


# ---- normative derivations ---------------------------------------------------

def work_id(intent: dict[str, Any]) -> str:
    return sha256_hex(WORK_DOMAIN + jcs_bytes(intent))


def authorization_hash(authorization: dict[str, Any]) -> str:
    return _signed_hash(authorization, ("value",))


def sign_authorization(authorization: dict[str, Any], seed: bytes) -> dict[str, Any]:
    out = copy.deepcopy(authorization)
    out.pop("value", None)
    digest = authorization_hash(out)
    out["value"] = b64u(ed25519_sign(seed, AUTH_DOMAIN + digest.encode("ascii")))
    return out


def receipt_hash(receipt: dict[str, Any]) -> str:
    return sha256_hex(jcs_bytes(receipt))


def operation_leaf_hash(leaf: dict[str, Any]) -> bytes:
    return sha256(b"\x00" + OP_RECEIPT_DOMAIN + jcs_bytes(leaf))


def merkle_root_from_hashes(hashes: list[bytes]) -> bytes:
    if not hashes:
        return sha256(b"")
    if len(hashes) == 1:
        return hashes[0]
    split = 1 << ((len(hashes) - 1).bit_length() - 1)
    return sha256(
        b"\x01"
        + merkle_root_from_hashes(hashes[:split])
        + merkle_root_from_hashes(hashes[split:])
    )


def operation_receipt_root(leaves: list[dict[str, Any]]) -> str:
    return merkle_root_from_hashes([operation_leaf_hash(v) for v in leaves]).hex()


def evaluate_merkle(data: dict[str, Any]) -> None:
    leaves = data.get("leaves")
    if not isinstance(leaves, list):
        raise Invalid("Merkle leaves unavailable")
    if data.get("claimedRoot") != operation_receipt_root(leaves):
        raise Invalid("operation receipt primitive root mismatch")
    for index, leaf in enumerate(leaves):
        if not verify_inclusion(leaf, inclusion_path(leaves, index), data["claimedRoot"]):
            raise Invalid("operation receipt primitive inclusion failed")


def _largest_split(count: int) -> int:
    return 1 << ((count - 1).bit_length() - 1)


def inclusion_path(leaves: list[dict[str, Any]], index: int) -> list[dict[str, str]]:
    if index < 0 or index >= len(leaves):
        raise IndexError(index)

    def walk(hashes: list[bytes], idx: int) -> tuple[bytes, list[dict[str, str]]]:
        if len(hashes) == 1:
            return hashes[0], []
        split = _largest_split(len(hashes))
        if idx < split:
            root, path = walk(hashes[:split], idx)
            sibling = merkle_root_from_hashes(hashes[split:])
            return sha256(b"\x01" + root + sibling), path + [{"side": "right", "hash": sibling.hex()}]
        root, path = walk(hashes[split:], idx - split)
        sibling = merkle_root_from_hashes(hashes[:split])
        return sha256(b"\x01" + sibling + root), path + [{"side": "left", "hash": sibling.hex()}]

    _, result = walk([operation_leaf_hash(v) for v in leaves], index)
    return result


def verify_inclusion(leaf: dict[str, Any], path: list[dict[str, str]], root: str) -> bool:
    value = operation_leaf_hash(leaf)
    for item in path:
        try:
            sibling = bytes.fromhex(item["hash"])
        except (KeyError, ValueError):
            return False
        if len(sibling) != 32:
            return False
        if item.get("side") == "right":
            value = sha256(b"\x01" + value + sibling)
        elif item.get("side") == "left":
            value = sha256(b"\x01" + sibling + value)
        else:
            return False
    return value.hex() == root


def state_root(state: dict[str, Any]) -> str:
    return sha256_hex(jcs_bytes(state))


def conflict_digest(conflict: dict[str, Any]) -> str:
    return sha256_hex(SLOT_DOMAIN + jcs_bytes(conflict))


_OPERATION_REF_FIELDS = {
    "kind", "networkId", "workId", "operationIndex", "operationId", "operationKind"
}


def settlement_id(operation_ref: dict[str, Any]) -> str:
    if not isinstance(operation_ref, dict) or not _OPERATION_REF_FIELDS.issubset(
        operation_ref
    ):
        raise Invalid("operationRef lacks the required v1 identity members")
    projected = {field: operation_ref[field] for field in (
        "kind", "networkId", "workId", "operationIndex", "operationId",
        "operationKind",
    )}
    if (
        projected["kind"] != "demos-work-operation-v1"
        or not isinstance(projected["networkId"], str)
        or not projected["networkId"]
        or not isinstance(projected["workId"], str)
        or not HEX_64.fullmatch(projected["workId"])
        or not isinstance(projected["operationIndex"], int)
        or isinstance(projected["operationIndex"], bool)
        or projected["operationIndex"] < 0
        or not isinstance(projected["operationId"], str)
        or not OP_ID.fullmatch(projected["operationId"])
        or projected["operationKind"] not in OP_KINDS
    ):
        raise Invalid("operationRef required v1 identity member is invalid")
    return sha256_hex(SETTLEMENT_ID_DOMAIN + jcs_bytes(projected))


def cf4_encode(value: str) -> str:
    out = value
    for char, encoded in (("%", "%25"), (":", "%3A"), ("?", "%3F"), ("&", "%26"), ("=", "%3D")):
        out = out.replace(char, encoded)
    return out


def cf4_decode(value: str) -> str:
    if re.search(r"%(?![0-9A-F]{2})", value):
        raise Malformed("non-canonical CF-4 escape")
    decoded = value
    for encoded, char in (("%3A", ":"), ("%3F", "?"), ("%26", "&"), ("%3D", "="), ("%25", "%")):
        decoded = decoded.replace(encoded, char)
    if cf4_encode(decoded) != value:
        raise Malformed("non-canonical CF-4 segment")
    return decoded


def _canonical_uint(value: str, label: str) -> int:
    if not isinstance(value, str) or not re.fullmatch(r"0|[1-9][0-9]*", value):
        raise Malformed(f"non-canonical {label}")
    number = int(value)
    if number > SAFE_INT_MAX:
        raise Malformed(f"unsafe {label}")
    return number


def parse_pc2_address(address: str) -> dict[str, Any]:
    if not isinstance(address, str):
        raise Malformed("PC2 address is not a string")
    parts = address.split(":")
    if len(parts) != 5 or parts[:2] != ["dacs4", "payment"]:
        raise Malformed("invalid ordinary PC2 address shape")
    if not JOB_ID.fullmatch(parts[2]):
        raise Malformed("PC2 jobId is not a ULID")
    return {
        "jobId": parts[2], "railId": cf4_decode(parts[3]),
        "phaseIndex": _canonical_uint(parts[4], "phaseIndex"),
    }


def atomic_evidence_address(evidence: dict[str, Any], generation: int | None = None) -> str:
    identity = settlement_id(evidence["operationRef"])
    if evidence.get("phase") == "pay-dem":
        if not isinstance(generation, int) or isinstance(generation, bool) or generation < 0:
            raise Malformed("payment generation unavailable")
        return (
            f"dacs4:payment:{evidence['jobId']}:{cf4_encode(evidence['railId'])}:"
            f"{evidence['phaseIndex']}:atomic:{generation}:{identity}"
        )
    if evidence.get("phase") == "deliver-storage-program":
        return f"dacs4:delivery:{evidence['jobId']}:{evidence['phaseIndex']}:atomic:{identity}"
    raise Invalid("unsupported Atomic evidence phase")


def verify_atomic_evidence_address(
    address: str, evidence: dict[str, Any], generation: int | None = None
) -> None:
    if not isinstance(address, str):
        raise Malformed("Atomic evidence address is not a string")
    parts = address.split(":")
    if evidence.get("phase") == "pay-dem":
        if len(parts) != 8 or parts[:2] != ["dacs4", "payment"] or parts[5] != "atomic":
            raise Malformed("invalid Atomic payment address shape")
        if not JOB_ID.fullmatch(parts[2]):
            raise Malformed("Atomic payment jobId is not a ULID")
        cf4_decode(parts[3])
        _canonical_uint(parts[4], "phaseIndex")
        parsed_generation = _canonical_uint(parts[6], "generation")
        if parsed_generation != generation:
            raise Invalid("Atomic payment address generation mismatch")
        if not HEX_64.fullmatch(parts[7]):
            raise Malformed("Atomic payment settlement ID is not lowercase hex")
    elif evidence.get("phase") == "deliver-storage-program":
        if len(parts) != 6 or parts[:2] != ["dacs4", "delivery"] or parts[4] != "atomic":
            raise Malformed("invalid Atomic delivery address shape")
        if not JOB_ID.fullmatch(parts[2]):
            raise Malformed("Atomic delivery jobId is not a ULID")
        _canonical_uint(parts[3], "phaseIndex")
        if not HEX_64.fullmatch(parts[5]):
            raise Malformed("Atomic delivery settlement ID is not lowercase hex")
    else:
        raise Invalid("unsupported Atomic evidence phase")
    if address != atomic_evidence_address(evidence, generation):
        raise Invalid("Atomic evidence address mismatch")


def _is_pure_json(value: Any) -> bool:
    if value is None or isinstance(value, (str, bool)):
        return True
    if isinstance(value, int) and not isinstance(value, bool):
        return abs(value) <= SAFE_INT_MAX
    if isinstance(value, list):
        return all(_is_pure_json(v) for v in value)
    if isinstance(value, dict):
        return all(isinstance(k, str) and _is_pure_json(v) for k, v in value.items())
    return False


def _ordered_unique(values: list[str], ordering: tuple[str, ...] = ROLE_ORDER) -> bool:
    if len(values) != len(set(values)) or any(v not in ordering for v in values):
        return False
    return [ordering.index(v) for v in values] == sorted(ordering.index(v) for v in values)


def validate_intent(intent: dict[str, Any], claimed: str | None = None) -> None:
    if not isinstance(intent, dict) or not _is_pure_json(intent):
        raise Invalid("intent is not pure safe-integer JSON")
    if intent.get("workVersion") != "1":
        raise Invalid("unsupported workVersion")
    if intent.get("profile") not in {"dacs-purchase-v1", "dacs-completion-v1"}:
        raise Invalid("unsupported profile")
    for field in ("executionProfile", "networkId", "railId", "jobId"):
        if not isinstance(intent.get(field), str) or not intent[field]:
            raise Invalid(f"invalid {field}")
    if not JOB_ID.fullmatch(intent["jobId"]):
        raise Invalid("jobId is not a canonical uppercase ULID")
    if not isinstance(intent.get("phaseIndex"), int) or isinstance(intent["phaseIndex"], bool):
        raise Invalid("phaseIndex is not an integer")
    if not isinstance(intent.get("expiresAt"), int) or isinstance(intent["expiresAt"], bool):
        raise Invalid("expiresAt is not an integer")
    roster = intent.get("roleRoster")
    if not isinstance(roster, list):
        raise Invalid("roleRoster missing")
    roles = [r.get("role") for r in roster if isinstance(r, dict)]
    if len(roles) != len(roster) or not _ordered_unique(roles):
        raise Invalid("roleRoster is not canonical and unique")
    for binding in roster:
        claim_key(binding.get("signer"))
    operations = intent.get("operations")
    if not isinstance(operations, list) or not operations:
        raise Invalid("operations missing")
    seen: set[str] = set()
    for index, operation in enumerate(operations):
        if not isinstance(operation, dict):
            raise Invalid("operation is not an object")
        operation_id = operation.get("operationId")
        if not isinstance(operation_id, str) or not OP_ID.fullmatch(operation_id):
            raise Invalid("invalid operationId")
        if operation_id in seen:
            raise Invalid("duplicate operationId")
        if operation.get("kind") not in OP_KINDS:
            raise Invalid("unknown operation kind")
        if operation.get("critical") is not True:
            raise Invalid("non-critical v1 operation")
        dependencies = operation.get("dependsOn")
        if not isinstance(dependencies, list) or len(dependencies) != len(set(dependencies)):
            raise Invalid("invalid dependency list")
        if any(dep not in seen for dep in dependencies):
            raise Invalid("dependency is unknown, self, or not earlier")
        required = operation.get("requiredRoles")
        if not isinstance(required, list) or not _ordered_unique(required):
            raise Invalid("requiredRoles is not canonical and unique")
        if any(role not in roles for role in required):
            raise Invalid("required role absent from roster")
        payload = operation.get("payload")
        if not isinstance(payload, dict) or "$runtime" in payload:
            raise Invalid("payload is not a pure portable data value")
        seen.add(operation_id)
    derived = work_id(intent)
    if claimed is not None and claimed != derived:
        raise Invalid("claimed workId does not match canonical bytes")
    if "priorFailureReceiptCommitment" in intent and not (
        isinstance(intent["priorFailureReceiptCommitment"], str)
        and HEX_64.fullmatch(intent["priorFailureReceiptCommitment"])
    ):
        raise Invalid("priorFailureReceiptCommitment is not a lowercase SHA-256 hash")


def verify_capability(
    capability: dict[str, Any], public_keys: dict[str, str],
    expected_network_authority: str | None = None,
) -> None:
    if expected_network_authority is None:
        raise Unknown("independently pinned network capability authority unavailable")
    if capability.get("networkAuthority") != claim_key(expected_network_authority):
        raise Invalid("capability network authority differs from trusted registry")
    unsigned = {k: v for k, v in capability.items() if k != "evidence"}
    attestation = verify_encoded_evidence(
        capability.get("evidence"), "test-network-capability-attestation",
        public_keys, _CAPABILITY_TEST_DOMAIN,
        expected_signer=expected_network_authority,
    )
    if attestation.get("capabilityHash") != sha256_hex(jcs_bytes(unsigned)):
        raise Invalid("capability attestation hash mismatch")
    if capability.get("capabilityVersion") != "1":
        raise Invalid("unsupported capability")
    claim_key(capability.get("networkAuthority"))
    if capability.get("workVersions") != ["1"]:
        raise Invalid("capability does not admit Work v1")
    if "ed25519" not in capability.get("authorizationAlgorithms", []):
        raise Invalid("capability does not admit the authorization algorithm")
    if not isinstance(capability.get("proofProfile"), str) or not capability["proofProfile"]:
        raise Invalid("capability proof profile missing")
    limits = capability.get("limits")
    if not isinstance(limits, dict) or any(
        not isinstance(limits.get(k), int) or isinstance(limits.get(k), bool) or limits[k] <= 0
        for k in (
            "maxCanonicalBytes", "maxOperations", "maxExecutionTimeMs",
            "maxProofBytes",
        )
    ):
        raise Invalid("invalid capability limits")


def validate_payload_schemas(
    intent: dict[str, Any], capability: dict[str, Any]
) -> None:
    """Validate every operation against the profile's advertised closed v1 schema."""
    if capability.get("executionProfile") != intent.get("executionProfile"):
        raise Invalid("payload schema execution profile mismatch")
    advertised = capability.get("payloadSchemas")
    if not isinstance(advertised, dict):
        raise Invalid("capability payloadSchemas missing")
    admitted = capability.get("operationKinds")
    if admitted != sorted(OP_KINDS):
        raise Invalid("capability operation-kind list is not the exact canonical v1 list")
    if advertised != PAYLOAD_SCHEMAS:
        raise Invalid("capability payload-schema map is not the exact v1 map")

    for operation in intent["operations"]:
        kind = operation["kind"]
        payload = operation["payload"]
        keys = set(payload)
        if kind == "assert-artifact":
            valid = keys == {"artifact"} and isinstance(payload.get("artifact"), dict)
        elif kind == "storage-program-put":
            write_condition = payload.get("writeCondition")
            condition_valid = isinstance(write_condition, dict) and (
                write_condition == {"kind": "create-only"}
                or (
                    set(write_condition) == {"kind", "expectedContentHash"}
                    and write_condition.get("kind") == "compare-and-set"
                    and isinstance(write_condition.get("expectedContentHash"), str)
                    and bool(HEX_64.fullmatch(write_condition["expectedContentHash"]))
                )
            )
            artifact_shape = (
                keys == {"artifact", "logicalAddress", "writeCondition"}
                and isinstance(payload.get("artifact"), dict)
            )
            bytes_shape = (
                keys == {"bytes", "contentHash", "logicalAddress", "writeCondition"}
                and isinstance(payload.get("bytes"), str)
                and isinstance(payload.get("contentHash"), str)
                and bool(HEX_64.fullmatch(payload["contentHash"]))
            )
            valid = condition_valid and (artifact_shape or bytes_shape) and isinstance(
                payload.get("logicalAddress"), str
            ) and bool(payload["logicalAddress"])
        elif kind == "payment-slot-cas":
            valid = (
                keys == {"slotKey", "expected", "conflictDigest"}
                and isinstance(payload.get("slotKey"), dict)
                and set(payload["slotKey"]) == {"networkId", "railId", "jobId", "phaseIndex"}
                and isinstance(payload.get("expected"), dict)
                and set(payload["expected"]) == {"state", "generation"}
                and payload["expected"].get("state") in {"vacant", "rolled-back"}
                and isinstance(payload["expected"].get("generation"), int)
                and not isinstance(payload["expected"].get("generation"), bool)
                and isinstance(payload.get("conflictDigest"), str)
                and bool(HEX_64.fullmatch(payload["conflictDigest"]))
            )
        elif kind == "native-dem-transfer":
            valid = keys == {"from", "to", "asset", "amount"} and all(
                isinstance(payload.get(field), str) and bool(payload[field])
                for field in ("from", "to", "asset", "amount")
            )
        elif kind == "assert-work-receipt":
            valid = keys == {"receipt"} and isinstance(payload.get("receipt"), dict)
        else:  # validate_intent rejects this first; retain fail-closed locality.
            valid = False
        if not valid:
            raise Invalid(f"payload does not conform to {advertised.get(kind)!r}")


def consume_capability_for_intent(
    intent: dict[str, Any], capability: dict[str, Any],
    public_keys: dict[str, str], expected_network_authority: str | None,
    expected_proof_profile: str | None,
) -> None:
    """Verify and scope an authenticated capability at every Work trust boundary."""
    validate_intent(intent)
    verify_capability(capability, public_keys, expected_network_authority)
    if capability.get("networkId") != intent.get("networkId"):
        raise Invalid("capability networkId does not admit the Work intent")
    if capability.get("executionProfile") != intent.get("executionProfile"):
        raise Invalid("capability executionProfile does not admit the Work intent")
    if intent.get("workVersion") not in capability.get("workVersions", []):
        raise Invalid("capability workVersions do not admit the Work intent")
    if intent.get("profile") not in capability.get("profiles", []):
        raise Invalid("capability profiles do not admit the Work intent")
    if not isinstance(expected_proof_profile, str) or not expected_proof_profile:
        raise Unknown("independently selected proof profile unavailable")
    if capability.get("proofProfile") != expected_proof_profile:
        raise Invalid("capability proofProfile differs from the selected verifier profile")
    validate_payload_schemas(intent, capability)


def evaluate_capability(data: dict[str, Any]) -> None:
    stage = data.get("stage")
    fallback = data.get("fallback", False)
    capability = data.get("capability")
    verified = False
    if isinstance(capability, dict):
        try:
            verify_capability(capability, data["publicKeys"], data.get("expectedNetworkAuthority"))
            intent = data.get("intent")
            if isinstance(intent, dict):
                consume_capability_for_intent(
                    intent, capability, data["publicKeys"],
                    data.get("expectedNetworkAuthority"), data.get("expectedProofProfile"),
                )
                verified = True
            else:
                verified = (
                    capability.get("networkId") == data.get("networkId")
                    and data.get("executionProfile") == capability.get("executionProfile")
                    and data.get("profile") in capability.get("profiles", [])
                    and data.get("expectedProofProfile") == capability.get("proofProfile")
                )
        except (Invalid, Unknown):
            verified = False
    if data.get("mode") == "legacy":
        if stage != "pre-sign":
            raise Invalid("legacy fallback after Atomic signature/submission")
        if not fallback:
            raise Invalid("legacy mode not selected")
        return
    if not verified:
        if stage == "pre-sign" and fallback:
            return
        raise Invalid("Atomic profile lacks verified matching capability")
    if fallback and stage in {"signed", "submitted"}:
        raise Invalid("silent fallback after Atomic work authorization")
    if data.get("businessWorks") != 2 or data.get("auditTail") is not True:
        raise Invalid("profile is two business Works plus an audit tail")
    if data.get("claimsExactlyTwoLifecycleTransactions") is True:
        raise Invalid("full lifecycle is not exactly two transactions")


def verify_authorizations(
    intent: dict[str, Any], authorizations: list[dict[str, Any]], public_keys: dict[str, str],
    authority: dict[str, Any] | None = None, capability: dict[str, Any] | None = None,
    expected_network_authority: str | None = None,
    expected_proof_profile: str | None = None,
) -> None:
    if not isinstance(capability, dict):
        raise Unknown("verified capability unavailable for authorization")
    consume_capability_for_intent(
        intent, capability, public_keys, expected_network_authority,
        expected_proof_profile,
    )
    if not isinstance(authority, dict):
        raise Unknown("independently authenticated role authority unavailable")
    agreement = authority.get("agreement")
    payer_bundle = authority.get("payerBundle")
    payment_input = authority.get("paymentPhaseInput")
    commitment = authority.get("finalityCommitment")
    commitment_receipt = authority.get("commitmentReceipt")
    session = authority.get("sessionContext")
    if not all(isinstance(value, dict) for value in (
        agreement, payer_bundle, payment_input, commitment, commitment_receipt,
    )):
        raise Unknown("verified agreement, payer bundle, payment input, and commitment required")
    _verify_agreement(agreement, public_keys)
    _verify_identity_bundle(payer_bundle, public_keys)
    _verify_finality_commitment(commitment, commitment_receipt, public_keys)
    if agreement.get("jobId") != intent["jobId"] or payment_input.get("jobId") != intent["jobId"]:
        raise Invalid("authorization authority jobId mismatch")
    derived = work_id(intent)
    roster = {r["role"]: r["signer"] for r in intent["roleRoster"]}
    agreement_roles = {p.get("role"): p for p in agreement.get("parties", [])}
    for role in ("buyer", "seller"):
        if roster.get(role) != agreement_roles.get(role, {}).get("primaryClaim"):
            raise Invalid("roster contradicts signed AgreementParty authority")
    orchestrator = claim_key(commitment.get("signature", {}).get("signer"))
    if roster.get("orchestrator") != orchestrator:
        raise Invalid("roster orchestrator contradicts finalized commitment signer")
    if isinstance(session, dict):
        session_orchestrators = [
            p.get("primaryClaim") for p in session.get("parties", [])
            if p.get("role") == "orchestrator"
        ]
        if session_orchestrators != [orchestrator]:
            raise Invalid("SessionContext orchestrator contradicts commitment signer")
    payer = payment_input.get("payer", {})
    paying_key = payer.get("payingKey")
    bundle_claims = [c.get("ref") for c in payer_bundle.get("claims", [])]
    buyer = agreement_roles.get("buyer", {})
    bundle_hash = _identity_bundle_hash(payer_bundle)
    if (
        roster.get("payer") != paying_key
        or paying_key not in bundle_claims
        or payer.get("bundleHash") != bundle_hash
        or payer.get("primaryClaim") != buyer.get("primaryClaim")
        or payer.get("bundleHash") != buyer.get("bundleHash")
    ):
        raise Invalid("payer authority is not bound to pinned buyer bundle and paying key")
    transfer = next((op for op in intent["operations"] if op["kind"] == "native-dem-transfer"), None)
    payer_roster = next((r for r in intent["roleRoster"] if r["role"] == "payer"), {})
    if isinstance(transfer, dict) and transfer["payload"].get("from") != payer_roster.get("nativeAccount"):
        raise Invalid("native transfer source does not match payer roster account")
    expected_pairs = {
        (i, role)
        for i, operation in enumerate(intent["operations"])
        for role in operation["requiredRoles"]
    }
    seen: set[tuple[int, str]] = set()
    for authorization in authorizations:
        if not isinstance(authorization, dict):
            raise Invalid("authorization is not an object")
        index = authorization.get("operationIndex")
        if not isinstance(index, int) or isinstance(index, bool) or not (0 <= index < len(intent["operations"])):
            raise Invalid("invalid authorization operationIndex")
        operation = intent["operations"][index]
        role = authorization.get("role")
        expected = {
            "authorizationVersion": "1",
            "workId": derived,
            "executionProfile": intent["executionProfile"],
            "networkId": intent["networkId"],
            "railId": intent["railId"],
            "jobId": intent["jobId"],
            "phaseIndex": intent["phaseIndex"],
            "operationId": operation["operationId"],
            "operationIndex": index,
            "operationKind": operation["kind"],
            "role": role,
            "signer": roster.get(role),
        }
        if authorization.get("algorithm") not in capability.get("authorizationAlgorithms", []):
            raise Invalid("authorization algorithm is not supported by verified capability")
        for field, value in expected.items():
            if authorization.get(field) != value:
                raise Invalid(f"authorization envelope mismatch: {field}")
        pair = (index, role)
        if pair not in expected_pairs or pair in seen:
            raise Invalid("unexpected or duplicate operation authorization")
        signer = claim_key(authorization.get("signer"))
        encoded_public = public_keys.get(signer)
        if encoded_public is None:
            raise Unknown("authorization key unavailable")
        digest = authorization_hash(authorization)
        if not ed25519_verify(
            _ed25519_public_bytes(encoded_public),
            AUTH_DOMAIN + digest.encode("ascii"),
            _ed25519_signature_bytes(authorization.get("value", "")),
        ):
            raise Invalid("invalid operation authorization signature")
        seen.add(pair)
    if seen != expected_pairs:
        raise Invalid("missing required operation authorization")


def _network_authority(data: dict[str, Any]) -> str:
    capability = data.get("capability")
    if not isinstance(capability, dict):
        raise Unknown("verified capability unavailable")
    verify_capability(capability, data["publicKeys"], data.get("expectedNetworkAuthority"))
    return claim_key(capability.get("networkAuthority"))


def _verify_ledger_evidence(
    evidence: dict[str, Any], public_keys: dict[str, str], expected_signer: str,
    expected_native_transaction_ref: dict[str, Any] | None,
) -> None:
    verify_embedded(evidence, public_keys, _LEDGER_TEST_DOMAIN)
    require_signer(evidence, expected_signer)
    native_ref = evidence.get("nativeTransactionRef")
    if (
        not isinstance(native_ref, dict)
        or set(native_ref) != {"kind", "value"}
        or not all(
            isinstance(native_ref.get(field), str) and native_ref[field]
            for field in ("kind", "value")
        )
    ):
        raise Invalid("lifecycle evidence nativeTransactionRef malformed")
    if not isinstance(expected_native_transaction_ref, dict):
        raise Unknown("independently expected nativeTransactionRef unavailable")
    if native_ref != expected_native_transaction_ref:
        raise Invalid("lifecycle evidence nativeTransactionRef mismatch")
    if evidence.get("state") not in {
        "authoritative-non-inclusion", "included-committed", "included-rolled-back"
    }:
        raise Invalid("unsupported attempt lifecycle state")


def evaluate_attempts(data: dict[str, Any]) -> None:
    intent = data["intent"]
    validate_intent(intent)
    wid = work_id(intent)
    canonical = canonicalize(intent)
    network_authority = _network_authority(data)
    attempts = data.get("attempts", [])
    by_id: dict[str, dict[str, Any]] = {}
    included: list[dict[str, Any]] = []
    for attempt in attempts:
        if attempt.get("attemptVersion") != "1":
            raise Invalid("unsupported attemptVersion")
        native_ref = attempt.get("nativeTransactionRef")
        if (
            not isinstance(native_ref, dict)
            or set(native_ref) != {"kind", "value"}
            or not all(isinstance(native_ref.get(k), str) and native_ref[k] for k in ("kind", "value"))
        ):
            raise Invalid("attempt nativeTransactionRef malformed")
        auths = attempt.get("authorizations")
        if not isinstance(auths, list):
            raise Unknown("attempt authorizations unavailable")
        verify_authorizations(
            intent, auths, data["publicKeys"], data.get("authority"), data.get("capability"),
            data.get("expectedNetworkAuthority"), data.get("expectedProofProfile"),
        )
        if attempt.get("workId") != wid or attempt.get("canonicalWorkBytes") != canonical:
            raise Invalid("attempt changes canonical Work bytes or workId")
        attempt_id = attempt.get("attemptId")
        if not isinstance(attempt_id, str) or attempt_id in by_id:
            raise Invalid("invalid or duplicate attemptId")
        by_id[attempt_id] = attempt
        evidence = attempt.get("lifecycleEvidence")
        if isinstance(evidence, dict):
            _verify_ledger_evidence(
                evidence, data["publicKeys"], network_authority, native_ref
            )
            if evidence.get("attemptId") != attempt_id or evidence.get("workId") != wid:
                raise Invalid("attempt evidence tuple mismatch")
            if evidence["state"].startswith("included-"):
                included.append(attempt)
    for attempt in attempts:
        replaced = attempt.get("replacementFor")
        if replaced is None:
            continue
        prior = by_id.get(replaced)
        if prior is None:
            raise Invalid("replacement names an unknown attempt")
        proof = prior.get("lifecycleEvidence")
        if proof is None and prior.get("observation") in {"not-found", "timeout", "expired-local"}:
            raise Unknown("ordinary observation cannot authorize replacement")
        if not isinstance(proof, dict):
            raise Unknown("replacement authority unavailable")
        _verify_ledger_evidence(
            proof, data["publicKeys"], network_authority,
            prior.get("nativeTransactionRef"),
        )
        if proof.get("state") != "authoritative-non-inclusion":
            raise Invalid("included or unresolved attempt cannot be replaced")
    if len(included) > 1:
        raise Invalid("ledger selected more than one included attempt")
    winner = data.get("winningAttemptId")
    if included and winner != included[0]["attemptId"]:
        raise Invalid("winner does not match authenticated ledger")
    if not included and winner is not None:
        raise Invalid("winner claimed without inclusion evidence")
    effects = data.get("businessEffectAttempts", [])
    if any(effect != winner for effect in effects) or len(effects) > (1 if winner else 0):
        raise Invalid("late/competing attempt was not fenced")
    for attempt in attempts:
        replay_of = attempt.get("replayOf")
        if replay_of is not None and winner is not None:
            if replay_of != winner or attempt.get("returnedWinner") != winner:
                raise Invalid("exact replay did not return selected winner")


def _receipt_commitment(receipt: dict[str, Any]) -> str:
    core = copy.deepcopy({
        k: v for k, v in receipt.items()
        if k not in {"receiptCommitment", "finalityEvidence"}
    })
    core.get("blockRef", {}).pop("id", None)
    core.get("businessState", {}).pop("evidence", None)
    core.pop("slotStateEvidence", None)
    if core.get("profile") == "dacs-purchase-v1":
        slot_after = core.get("paymentSlot", {}).get("after", {})
        slot_after.pop("receiptCommitment", None)
        slot_after.pop("failureReceiptCommitment", None)
    return sha256_hex(WORK_RECEIPT_DOMAIN + jcs_bytes(core))


def _validated_storage_output(
    operation: dict[str, Any], result: dict[str, Any]
) -> dict[str, Any]:
    """Return the complete Demos storage result only after binding validation."""
    output = result.get("storageOutput")
    required = {"logicalAddress", "nativeAddress", "contentHash", "writer", "nonce"}
    if not isinstance(output, dict) or not required.issubset(output):
        raise Invalid("committed storage operation lacks complete storageOutput")
    if any(
        not isinstance(output.get(field), str) or not output[field]
        for field in ("logicalAddress", "nativeAddress", "writer", "nonce")
    ) or not isinstance(output.get("contentHash"), str) or not HEX_64.fullmatch(
        output["contentHash"]
    ):
        raise Invalid("committed storage operation has malformed storageOutput")
    payload = operation.get("payload", {})
    expected_content_hash = payload.get("contentHash")
    if expected_content_hash is None and isinstance(payload.get("artifact"), dict):
        expected_content_hash = sha256_hex(jcs_bytes(payload["artifact"]))
    if (
        output["logicalAddress"] != payload.get("logicalAddress")
        or output["contentHash"] != expected_content_hash
    ):
        raise Invalid("storageOutput contradicts the signed storage payload")
    return output


def verify_receipt(
    receipt: dict[str, Any], intent: dict[str, Any], public_keys: dict[str, str],
    *, capability: dict[str, Any] | None = None,
    purchase_intent: dict[str, Any] | None = None,
    purchase_receipt: dict[str, Any] | None = None,
    expected_network_authority: str | None = None,
    expected_proof_profile: str | None = None,
) -> None:
    if not isinstance(capability, dict):
        raise Unknown("verified capability/proof profile unavailable")
    consume_capability_for_intent(
        intent, capability, public_keys, expected_network_authority,
        expected_proof_profile,
    )
    proof_profile = expected_proof_profile
    network_authority = claim_key(capability["networkAuthority"])
    if receipt.get("receiptVersion") != "1":
        raise Invalid("unsupported receipt version")
    block_timestamp = receipt.get("blockRef", {}).get("timestamp")
    if not isinstance(block_timestamp, int) or isinstance(block_timestamp, bool):
        raise Invalid("receipt block timestamp invalid")
    if block_timestamp >= intent.get("expiresAt", -1):
        raise Invalid("Work execution is expired at consensus transition")
    if receipt.get("workId") != work_id(intent):
        raise Invalid("receipt workId mismatch")
    for field in ("executionProfile", "profile", "networkId"):
        if receipt.get(field) != intent.get(field):
            raise Invalid(f"receipt {field} mismatch")
    results = receipt.get("operationResults")
    if not isinstance(results, list) or len(results) != len(intent["operations"]):
        raise Invalid("receipt operation count mismatch")
    for index, (operation, result) in enumerate(zip(intent["operations"], results)):
        if (
            result.get("operationId") != operation["operationId"]
            or result.get("operationIndex") != index
            or result.get("operationKind") != operation["kind"]
        ):
            raise Invalid("receipt operation order or identity mismatch")
        if result.get("inputHash") != sha256_hex(jcs_bytes(operation["payload"])):
            raise Invalid("operation receipt inputHash mismatch")
        if result.get("status") == "committed":
            if operation["kind"] == "storage-program-put":
                storage_output = _validated_storage_output(operation, result)
                expected_output = sha256_hex(jcs_bytes(storage_output))
            elif operation["kind"] == "native-dem-transfer":
                expected_output = sha256_hex(jcs_bytes(operation["payload"]))
            else:
                expected_output = sha256_hex(jcs_bytes({
                    "accepted": True, "operationId": operation["operationId"],
                }))
            if result.get("outputHash") != expected_output:
                raise Invalid("synthetic proof profile outputHash mismatch")
    if receipt.get("operationReceiptRoot") != operation_receipt_root(results):
        raise Invalid("operationReceiptRoot mismatch")
    business = receipt.get("businessState", {})
    witness_ref = business.get("evidence")
    if not isinstance(witness_ref, dict):
        raise Unknown("business-state witness unavailable")
    if witness_ref.get("kind") != "test-business-state-witness":
        raise Invalid("business-state evidence kind mismatch")
    try:
        witness = json.loads(b64u_decode(witness_ref.get("value", "")).decode("utf-8"))
    except (Invalid, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise Invalid("business-state witness encoding invalid") from exc
    if not isinstance(witness, dict):
        raise Invalid("business-state witness is not an object")
    verify_embedded(witness, public_keys, _STATE_TEST_DOMAIN)
    require_signer(witness, network_authority)
    pre_state, post_state = witness.get("preState"), witness.get("postState")
    if not isinstance(pre_state, dict) or not isinstance(post_state, dict):
        raise Invalid("invalid business-state witness")
    if business.get("preRoot") != state_root(pre_state) or business.get("postRoot") != state_root(post_state):
        raise Invalid("business-state root mismatch")
    if business.get("effectsRoot") != sha256_hex(jcs_bytes({"pre": pre_state, "post": post_state})):
        raise Invalid("synthetic proof profile effectsRoot mismatch")
    outcome = receipt.get("outcome")
    slot = receipt.get("paymentSlot")
    if not isinstance(slot, dict):
        raise Invalid("receipt paymentSlot transition missing")
    if intent["profile"] == "dacs-purchase-v1":
        slot_operations = [
            operation for operation in intent["operations"]
            if operation.get("kind") == "payment-slot-cas"
        ]
        if len(slot_operations) != 1:
            raise Invalid("Purchase Work does not carry exactly one signed payment slot")
        signed_slot_payload = slot_operations[0]["payload"]
        expected_slot_key = signed_slot_payload["slotKey"]
    else:
        embedded = intent.get("operations", [{}])[0].get("payload", {}).get("receipt")
        if not isinstance(purchase_receipt, dict) or not isinstance(purchase_intent, dict):
            raise Unknown("verified Purchase intent and receipt unavailable for Completion")
        if embedded != purchase_receipt:
            raise Invalid("Completion embedded receipt differs from verified Purchase receipt")
        if purchase_intent.get("profile") != "dacs-purchase-v1":
            raise Invalid("Completion prior Work is not a Purchase profile")
        for field in ("networkId", "railId", "jobId"):
            if purchase_intent.get(field) != intent.get(field):
                raise Invalid("Completion/Purchase tuple mismatch")
        verify_receipt(
            purchase_receipt, purchase_intent, public_keys, capability=capability,
            expected_network_authority=expected_network_authority,
            expected_proof_profile=expected_proof_profile,
        )
        payment = next((r for r in purchase_receipt.get("operationResults", []) if r.get("operationKind") == "native-dem-transfer"), None)
        if purchase_receipt.get("outcome") != "committed" or not isinstance(payment, dict) or payment.get("status") != "committed":
            raise Invalid("Completion prior Purchase lacks committed native transfer")
        expected_slot_key = purchase_receipt.get("paymentSlot", {}).get("key")
    if slot.get("key") != expected_slot_key:
        raise Invalid("receipt paymentSlot key does not match Work intent")
    if not isinstance(slot.get("before"), dict) or not isinstance(slot.get("after"), dict):
        raise Invalid("receipt paymentSlot before/after are not structured states")
    slot_proof = verify_encoded_evidence(
        receipt.get("slotStateEvidence"), "test-payment-slot-state",
        public_keys, _SLOT_STATE_TEST_DOMAIN, expected_signer=network_authority,
    )
    expected_slot_subject = copy.deepcopy(slot)
    if intent["profile"] == "dacs-purchase-v1":
        expected_slot_subject["after"].pop("receiptCommitment", None)
        expected_slot_subject["after"].pop("failureReceiptCommitment", None)
    if (
        slot_proof.get("slot") != expected_slot_subject
        or slot_proof.get("networkId") != intent["networkId"]
        or slot_proof.get("workId") != receipt["workId"]
        or slot_proof.get("proofProfile") != proof_profile
    ):
        raise Invalid("slot-state proof subject mismatch")
    statuses = [result.get("status") for result in results]
    if outcome == "committed":
        if any(status != "committed" for status in statuses):
            raise Invalid("committed receipt has non-committed operation")
        if intent["profile"] == "dacs-purchase-v1":
            expected_before = signed_slot_payload["expected"]
            expected_after = {
                "state": "settled",
                "generation": expected_before["generation"],
                "workId": receipt["workId"],
                "conflictDigest": signed_slot_payload["conflictDigest"],
                "receiptCommitment": receipt.get("receiptCommitment"),
            }
            if slot["before"] != expected_before or slot["after"] != expected_after:
                raise Invalid("committed Purchase slot transition contradicts signed CAS payload")
        elif slot["before"] != slot["after"]:
            raise Invalid("Completion Work unexpectedly changed payment slot")
    elif outcome == "rolled-back":
        if pre_state != post_state:
            raise Invalid("rolled-back receipt changed business state")
        failed = receipt.get("failedOperationId")
        if failed not in [op["operationId"] for op in intent["operations"]]:
            raise Invalid("rolled-back receipt lacks failed operation")
        failed_index = [op["operationId"] for op in intent["operations"]].index(failed)
        for i, status in enumerate(statuses):
            wanted = "rolled-back" if i <= failed_index else "not-executed"
            if status != wanted:
                raise Invalid("rollback leaf status mismatch")
        for protected in witness.get("protectedKeys", []):
            if pre_state.get(protected, {"absent": True}) != post_state.get(protected, {"absent": True}):
                raise Invalid("rollback output changed or non-membership contradicted")
        if intent["profile"] == "dacs-purchase-v1":
            expected_before = signed_slot_payload["expected"]
            expected_after = {
                "state": "rolled-back",
                "generation": expected_before["generation"],
                "workId": receipt["workId"],
                "conflictDigest": signed_slot_payload["conflictDigest"],
                "failureReceiptCommitment": receipt.get("receiptCommitment"),
            }
            if slot["before"] != expected_before or slot["after"] != expected_after:
                raise Invalid("rolled-back Purchase slot transition contradicts signed CAS payload")
        elif slot["before"] != slot["after"]:
            raise Invalid("rolled-back Completion changed Purchase slot metadata")
    else:
        raise Invalid("invalid receipt outcome")
    envelope = receipt.get("envelopeEffects")
    if not isinstance(envelope, dict) or not isinstance(envelope.get("nonceConsumed"), bool):
        raise Invalid("missing separate envelope effects")
    evidence = receipt.get("finalityEvidence")
    if receipt.get("receiptCommitment") != _receipt_commitment(receipt):
        raise Invalid("receiptCommitment does not match canonical receipt core")
    checkpoint = verify_encoded_evidence(
        evidence, "test-bft-checkpoint", public_keys, _CHECKPOINT_TEST_DOMAIN,
        expected_signer=network_authority,
    )
    if (
        checkpoint.get("networkId") != receipt.get("networkId")
        or checkpoint.get("blockId") != receipt.get("blockRef", {}).get("id")
        or checkpoint.get("receiptCommitment") != receipt.get("receiptCommitment")
        or checkpoint.get("proofProfile") != proof_profile
        or checkpoint.get("validatorSetId") != capability.get("validatorSetId")
    ):
        raise Invalid("finality checkpoint does not bind receipt")


def evaluate_receipt(data: dict[str, Any]) -> None:
    if data.get("receiptAvailability") == "unavailable":
        raise Unknown("receipt service unavailable; consensus reconstruction not supplied")
    verify_receipt(
        data["receipt"], data["intent"], data["publicKeys"],
        capability=data.get("capability"), purchase_intent=data.get("purchaseIntent"),
        purchase_receipt=data.get("purchaseReceipt"),
        expected_network_authority=data.get("expectedNetworkAuthority"),
        expected_proof_profile=data.get("expectedProofProfile"),
    )
    if data.get("authorizesResubmission") is True:
        raise Invalid("receipt/fee/nonce state cannot authorize resubmission")
    if data.get("claimsOtherAttemptAbsent") is True and data["receipt"].get("outcome") == "rolled-back":
        raise Invalid("included rollback does not prove other-attempt absence")


def evaluate_lifecycle(data: dict[str, Any]) -> None:
    evidence = data.get("evidence")
    if not isinstance(evidence, dict):
        raise Unknown("lifecycle/non-inclusion evidence unavailable")
    _verify_ledger_evidence(
        evidence, data["publicKeys"], _network_authority(data),
        data.get("nativeTransactionRef"),
    )
    if evidence.get("attemptId") != data.get("attemptId"):
        raise Invalid("lifecycle evidence attempt mismatch")
    if data.get("claimedState") != evidence.get("state"):
        raise Invalid("claimed lifecycle state contradicts evidence")


def evaluate_recovery(data: dict[str, Any]) -> None:
    boundary = data.get("crashBoundary")
    if boundary == "before-durable-admission":
        if data.get("inferredAbsent"):
            raise Invalid("crash before admission does not prove absence")
    elif boundary == "during-overlay":
        if data.get("preState") != data.get("postRecoveryState"):
            raise Invalid("overlay crash leaked a business effect")
    elif boundary == "after-consensus-commit":
        if data.get("recoveredReceiptHash") != data.get("committedReceiptHash"):
            raise Invalid("recovery changed committed receipt")
        if data.get("recoveredWinner") != data.get("committedWinner"):
            raise Invalid("recovery changed winner")
    else:
        raise Invalid("unknown crash boundary")


def evaluate_projection(data: dict[str, Any]) -> None:
    receipt = data["receipt"]
    intent = data["intent"]
    verify_receipt(
        receipt, intent, data["publicKeys"], capability=data.get("capability"),
        purchase_intent=data.get("purchaseIntent"), purchase_receipt=data.get("purchaseReceipt"),
        expected_network_authority=data.get("expectedNetworkAuthority"),
        expected_proof_profile=data.get("expectedProofProfile"),
    )
    evidence = data.get("operationEvidence")
    if not isinstance(evidence, dict):
        raise Unknown("operation inclusion evidence unavailable")
    leaf = evidence.get("leaf")
    if not isinstance(leaf, dict) or not verify_inclusion(
        leaf, evidence.get("inclusionPath", []), receipt["operationReceiptRoot"]
    ):
        raise Invalid("operation leaf inclusion proof invalid")
    operation_index = leaf.get("operationIndex")
    if (
        not isinstance(operation_index, int)
        or isinstance(operation_index, bool)
        or not (0 <= operation_index < len(intent["operations"]))
        or receipt["operationResults"][operation_index] != leaf
        or leaf.get("status") != "committed"
        or leaf.get("operationKind") != "storage-program-put"
    ):
        raise Invalid("projection leaf is not the committed receipt storage result")
    anchor = data.get("anchorReceipt", {})
    storage = _validated_storage_output(intent["operations"][operation_index], leaf)
    required_anchor_fields = {
        "receiptVersion", "substrate", "finalityProfile", "logicalAddress",
        "nativeAddress", "contentHash", "transactionRef", "writer", "nonce",
        "state", "observationDisposition", "observedAt", "blockRef", "evidence",
    }
    if not isinstance(anchor, dict) or set(anchor) != required_anchor_fields:
        raise Invalid("projection is not the complete finalized CORE AnchorReceipt shape")
    for field in ("logicalAddress", "nativeAddress", "contentHash", "writer", "nonce"):
        if anchor.get(field) != storage.get(field):
            raise Invalid(f"projection changed {field}")
    if (
        anchor.get("receiptVersion") != "1"
        or anchor.get("substrate") != receipt.get("networkId")
        or anchor.get("finalityProfile") != data.get("expectedProofProfile")
        or anchor.get("state") != "finalized"
        or anchor.get("observationDisposition") != "established"
        or anchor.get("blockRef") != receipt.get("blockRef")
        or not isinstance(anchor.get("observedAt"), int)
        or isinstance(anchor.get("observedAt"), bool)
        or anchor["observedAt"] < receipt.get("blockRef", {}).get("timestamp", 0)
    ):
        raise Invalid("projection changed receipt finality/lifecycle context")
    transaction_ref = anchor.get("transactionRef", {})
    expected_value = f"{receipt['workId']}/{leaf['operationId']}"
    if transaction_ref != {
        "kind": "demos-work-operation-v1", "value": expected_value
    }:
        raise Invalid("projection operation reference mismatch")
    anchor_evidence = anchor.get("evidence")
    if not isinstance(anchor_evidence, dict):
        raise Unknown("projected receipt does not resolve Work evidence")
    if anchor_evidence.get("kind") != "demos-work-operation-proof-v1":
        raise Invalid("projected receipt evidence kind mismatch")
    try:
        resolved = json.loads(b64u_decode(anchor_evidence.get("value", "")).decode("utf-8"))
    except (Invalid, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise Invalid("projected receipt evidence encoding invalid") from exc
    expected_operation_ref = {
        "kind": "demos-work-operation-v1",
        "networkId": receipt["networkId"],
        "workId": receipt["workId"],
        "operationIndex": operation_index,
        "operationId": leaf["operationId"],
        "operationKind": leaf["operationKind"],
    }
    if (
        not isinstance(resolved, dict)
        or set(resolved) != {
            "operationRef", "receiptContentHash", "leaf", "inclusionPath",
            "finalityEvidence",
        }
        or resolved.get("operationRef") != expected_operation_ref
        or resolved.get("receiptContentHash") != receipt_hash(receipt)
        or resolved.get("leaf") != leaf
        or resolved.get("inclusionPath") != evidence.get("inclusionPath", [])
        or resolved.get("finalityEvidence") != receipt.get("finalityEvidence")
    ):
        raise Invalid("projected receipt evidence does not resolve verified Work proof")


def _verify_artifact(artifact: dict[str, Any], public_keys: dict[str, str]) -> None:
    verify_embedded(artifact, public_keys, _ARTIFACT_TEST_DOMAIN)
    disclosed = artifact.get("contentHash")
    body = artifact.get("body")
    if disclosed != sha256_hex(jcs_bytes(body)):
        raise Invalid("artifact contentHash mismatch")


def _identity_bundle_hash(bundle: dict[str, Any]) -> str:
    return sha256_hex(jcs_bytes({k: v for k, v in bundle.items() if k != "presentation"}))


def _verify_identity_bundle(bundle: dict[str, Any], public_keys: dict[str, str]) -> None:
    if bundle.get("bundleVersion") != "1" or not isinstance(bundle.get("claims"), list):
        raise Invalid("pinned payer IdentityBundle malformed")
    presented = claim_key(bundle.get("presentedBy"))
    refs = [claim_key(c.get("ref")) for c in bundle["claims"] if isinstance(c, dict)]
    if presented not in refs:
        raise Invalid("IdentityBundle presentedBy missing from claims")
    presentation = bundle.get("presentation", {})
    if presentation.get("kind") != "per-claim":
        raise Invalid("synthetic profile requires per-claim IdentityBundle proof")
    message = b"dacs-bundle-presentation:v1:" + _identity_bundle_hash(bundle).encode("ascii")
    signatures = presentation.get("signatures", [])
    match = next((s for s in signatures if s.get("ref") == presented), None)
    key = public_keys.get(presented)
    if not isinstance(match, dict) or key is None:
        raise Unknown("payer IdentityBundle presentation key unavailable")
    if not ed25519_verify(
        _ed25519_public_bytes(key), message,
        _ed25519_signature_bytes(match.get("signature", "")),
    ):
        raise Invalid("payer IdentityBundle presentation signature invalid")


def _bundle_native_account(
    bundle: dict[str, Any], claim: str, account_role: str,
) -> str:
    """Resolve one authenticated native-account mapping without caller inference."""
    matches = [
        candidate for candidate in bundle.get("claims", [])
        if isinstance(candidate, dict) and candidate.get("ref") == claim
    ]
    if len(matches) != 1:
        raise Unknown(
            f"unique authenticated {account_role} native-account claim unavailable"
        )
    account = matches[0].get("metadata", {}).get("nativeAccount")
    if not isinstance(account, str) or not account:
        raise Unknown(f"authenticated {account_role} native account unavailable")
    return account


def _agreement_hash(agreement: dict[str, Any]) -> str:
    return sha256_hex(jcs_bytes({k: v for k, v in agreement.items() if k != "signatures"}))


def _verify_agreement(agreement: dict[str, Any], public_keys: dict[str, str]) -> None:
    if agreement.get("agreementVersion") != "1" or "payeeBoundAgreementVersion" in agreement:
        raise Invalid("authority is not a legacy AgreementDocument")
    parties = agreement.get("parties")
    if not isinstance(parties, list):
        raise Invalid("AgreementDocument parties missing")
    party_map = {p.get("role"): p for p in parties if isinstance(p, dict)}
    if set(party_map) != {"buyer", "seller"}:
        raise Invalid("AgreementDocument buyer/seller authority missing")
    digest = _agreement_hash(agreement)
    sigs = agreement.get("signatures")
    if not isinstance(sigs, list):
        raise Unknown("AgreementDocument signatures unavailable")
    by_party = {s.get("party"): s for s in sigs if isinstance(s, dict)}
    for role in ("buyer", "seller"):
        signer = claim_key(party_map[role].get("primaryClaim"))
        sig = by_party.get(signer)
        key = public_keys.get(signer)
        if not isinstance(sig, dict) or key is None:
            raise Unknown("required AgreementSignature unavailable")
        if sig.get("algorithm") != "ed25519" or not ed25519_verify(
            _ed25519_public_bytes(key), _AGREEMENT_DOMAIN + digest.encode("ascii"),
            _ed25519_signature_bytes(sig.get("value", "")),
        ):
            raise Invalid("AgreementSignature invalid")


def _verify_anchor_receipt(
    receipt: dict[str, Any], *, logical: str, content_hash: str,
) -> None:
    required = {
        "receiptVersion": "1", "logicalAddress": logical,
        "contentHash": content_hash, "state": "finalized",
        "observationDisposition": "established",
    }
    if any(receipt.get(k) != v for k, v in required.items()):
        raise Invalid("AnchorReceipt does not establish finalized artifact binding")
    for key in (
        "substrate", "finalityProfile", "nativeAddress", "transactionRef",
        "writer", "observedAt", "blockRef", "evidence",
    ):
        if key not in receipt:
            raise Invalid(f"AnchorReceipt missing {key}")


def _verify_finality_commitment(
    record: dict[str, Any], anchor_receipt: dict[str, Any], public_keys: dict[str, str]
) -> None:
    if record.get("finalityCommitmentVersion") != "1":
        raise Invalid("FinalityCommitmentRecord discriminator invalid")
    verify_embedded(record, public_keys, _COMMITMENT_DOMAIN)
    _verify_anchor_receipt(
        anchor_receipt, logical=f"dacs3:commit:{record.get('jobId')}",
        content_hash=sha256_hex(jcs_bytes(record)),
    )


def _verify_commitment_subject(
    record: dict[str, Any], agreement: dict[str, Any], job_id: str,
) -> None:
    if (
        record.get("jobId") != job_id
        or record.get("agreementHash") != _agreement_hash(agreement)
        or record.get("listingRef") != agreement.get("listingRef")
    ):
        raise Invalid("finality commitment does not bind exact job/agreement/listing tuple")


def _verify_composite_record(
    record: dict[str, Any], public_keys: dict[str, str], *, job_id: str,
    evaluated_party: str, bundle_hash: str, verifier: str,
) -> None:
    if record.get("recordVersion") != "1":
        raise Invalid("Vet artifact is not a CompositeVerificationRecord v1")
    verify_embedded(record, public_keys, _COMPOSITE_DOMAIN)
    require_signer(record, verifier)
    if (
        record.get("jobId") != job_id
        or claim_key(record.get("evaluatedParty")) != claim_key(evaluated_party)
        or record.get("bundleHash") != bundle_hash
    ):
        raise Invalid("CompositeVerificationRecord subject/bundle binding mismatch")
    if (
        not isinstance(record.get("requirementHash"), str)
        or not HEX_64.fullmatch(record["requirementHash"])
        or not all(isinstance(record.get(field), list) for field in (
            "freshness", "supplementary", "dealSpecific",
        ))
        or not isinstance(record.get("generatedAt"), int)
        or isinstance(record.get("generatedAt"), bool)
    ):
        raise Invalid("CompositeVerificationRecord is incomplete")
    if record.get("overallDecision") != "pass":
        raise Invalid("CompositeVerificationRecord does not establish a pass decision")


def _verify_listing(listing: dict[str, Any], public_keys: dict[str, str]) -> None:
    if listing.get("dacsVersion") != "1" or not isinstance(listing.get("pipeline"), list):
        raise Invalid("pinned Listing malformed")
    seller_bundle = listing.get("seller", {}).get("identity")
    if not isinstance(seller_bundle, dict):
        raise Unknown("Listing seller IdentityBundle unavailable")
    _verify_identity_bundle(seller_bundle, public_keys)
    digest = sha256_hex(jcs_bytes({k: v for k, v in listing.items() if k != "signature"}))
    signature = listing.get("signature", {})
    signer = claim_key(signature.get("signer"))
    if signer != seller_bundle.get("presentedBy"):
        raise Invalid("Listing signer does not match seller IdentityBundle")
    key = public_keys.get(signer)
    if key is None:
        raise Unknown("Listing signer key unavailable")
    if signature.get("algorithm") != "ed25519" or not ed25519_verify(
        _ed25519_public_bytes(key), _LISTING_DOMAIN + digest.encode("ascii"),
        _ed25519_signature_bytes(signature.get("value", "")),
    ):
        raise Invalid("Listing signature invalid")


def _verify_agreement_listing(
    agreement: dict[str, Any], listing: dict[str, Any], committed_at: int
) -> None:
    listing_hash = sha256_hex(jcs_bytes({k: v for k, v in listing.items() if k != "signature"}))
    if agreement.get("listingRef") != {
        "listingId": listing.get("listingId"), "version": listing.get("listingVersion"),
        "contentHash": listing_hash,
    }:
        raise Invalid("Agreement does not pin exact Listing")
    terms = agreement.get("terms", {})
    price = terms.get("price", {})
    listing_price = listing.get("pricing", {}).get("price", {})
    # §8.5.2 checks 1 and 2: fixed-price currency and exact amount.
    if price.get("currency") != listing_price.get("currency"):
        raise Invalid("Agreement currency differs from Listing")
    if price != listing_price:
        raise Invalid("Agreement fixed price differs from Listing")
    # Check 3: one selected pay rail appears in the pipeline and accepted set.
    pay_steps = [s for s in listing["pipeline"] if str(s.get("kind", "")).startswith("pay-")]
    accepted = listing.get("acceptedRails", [])
    rail = terms.get("rail")
    if (
        len(pay_steps) != 1 or not isinstance(rail, dict)
        or pay_steps[0].get("parameters", {}).get("rail") != rail.get("railId")
        or rail not in accepted
    ):
        raise Invalid("Agreement rail does not match pinned Listing pipeline")
    # Check 4: exact DeliverableSpec kind/hash/schema.
    spec = listing.get("offering", {}).get("deliverable", {})
    deliverable = terms.get("deliverable", {})
    expected_deliverable = {
        "deliverableType": spec.get("kind"), "hash": sha256_hex(jcs_bytes(spec)),
    }
    if "schemaUrl" in spec:
        expected_deliverable["schemaUrl"] = spec["schemaUrl"]
    if deliverable != expected_deliverable:
        raise Invalid("Agreement deliverable differs from Listing DeliverableSpec")
    # Checks 5 and 6: objective receipt time, deadline, and listing expiry.
    deadline_seconds = listing.get("terms", {}).get("deadlineSecAfterCommit")
    if not isinstance(deadline_seconds, int) or terms.get("deadline", SAFE_INT_MAX) > committed_at + deadline_seconds * 1000:
        raise Invalid("Agreement deadline exceeds Listing commitment-relative bound")
    not_after = listing.get("validity", {}).get("notAfter")
    if not_after is not None and not_after < committed_at:
        raise Invalid("Listing expired before commitment")
    # Check 7: fixed pipeline mapping.
    negotiate = [s.get("kind") for s in listing["pipeline"] if str(s.get("kind", "")).startswith("negotiate-")]
    if negotiate != ["negotiate-fixed-price"] or agreement.get("derivedFromPattern") != "fixed-price":
        raise Invalid("Agreement pattern differs from Listing pipeline")
    # Check 8 is inapplicable only because the signed pattern is fixed-price.
    if agreement.get("derivedFromPattern") == "sealed-envelope":
        raise Invalid("synthetic fixed-price fixture cannot establish sealed role direction")
    # Check 9: legacy AgreementDocument must pair with commit-agreement exactly.
    commit_steps = [s.get("kind") for s in listing["pipeline"] if str(s.get("kind", "")).startswith("commit-")]
    if commit_steps != ["commit-agreement"] or agreement.get("agreementVersion") != "1" or "payeeBoundAgreementVersion" in agreement:
        raise Invalid("Agreement artifact discriminator mismatches commitment phase")


def _profile_shape(intent: dict[str, Any], profile: str) -> None:
    if profile == "dacs-purchase-v1":
        expected = [
            ("buyer-vet", {"assert-artifact", "storage-program-put"}, [], ["orchestrator"]),
            ("seller-vet", {"assert-artifact", "storage-program-put"}, [], ["orchestrator"]),
            ("agreement", {"assert-artifact"}, ["buyer-vet", "seller-vet"], ["orchestrator"]),
            ("commitment", {"storage-program-put"}, ["agreement"], ["orchestrator"]),
            ("payment-slot", {"payment-slot-cas"}, ["commitment"], ["payer"]),
            ("payment", {"native-dem-transfer"}, ["payment-slot"], ["payer"]),
        ]
    else:
        expected = [
            ("purchase-receipt", {"assert-work-receipt"}, [], ["orchestrator"]),
            ("delivery", {"storage-program-put"}, ["purchase-receipt"], ["seller"]),
        ]
    operations = intent.get("operations", [])
    if len(operations) != len(expected):
        raise Invalid("profile operation count mismatch")
    for operation, (op_id, kinds, deps, roles) in zip(operations, expected):
        if (
            operation.get("operationId") != op_id
            or operation.get("kind") not in kinds
            or operation.get("dependsOn") != deps
            or operation.get("requiredRoles") != roles
        ):
            raise Invalid("profile operation order/dependencies/roles mismatch")


def evaluate_profile(data: dict[str, Any]) -> None:
    intent = data["intent"]
    validate_intent(intent)
    _profile_shape(intent, intent["profile"])
    listing = data.get("listing")
    if not isinstance(listing, dict):
        raise Unknown("verified pinned Listing unavailable")
    _verify_listing(listing, data["publicKeys"])
    if intent["profile"] == "dacs-purchase-v1":
        phases = [
            {"kind": step.get("kind"), "railId": step.get("parameters", {}).get("rail"), "index": i}
            for i, step in enumerate(listing.get("pipeline", []))
            if step.get("kind") == "pay-dem"
        ]
        if len(phases) != 1 or (
            phases[0].get("railId") != intent["railId"]
            or phases[0].get("index") != intent["phaseIndex"]
        ):
            raise Invalid("Purchase signed Listing pay-dem phase tuple mismatch")
        agreement = intent["operations"][2].get("payload", {}).get("artifact")
        if not isinstance(agreement, dict):
            raise Invalid("AgreementDocument bytes are incomplete")
        _verify_agreement(agreement, data["publicKeys"])
        agreement_parties = {
            party.get("role"): party
            for party in agreement.get("parties", [])
            if isinstance(party, dict)
        }
        for index, role in ((0, "buyer"), (1, "seller")):
            operation = intent["operations"][index]
            record = operation.get("payload", {}).get("artifact")
            party = agreement_parties.get(role, {})
            if not isinstance(record, dict):
                raise Invalid("Vet CompositeVerificationRecord bytes are incomplete")
            _verify_composite_record(
                record, data["publicKeys"], job_id=intent["jobId"],
                evaluated_party=party.get("primaryClaim"),
                bundle_hash=party.get("bundleHash"),
                verifier=data.get("authenticatedOrchestrator"),
            )
            if operation.get("kind") == "storage-program-put":
                expected_address = (
                    f"dacs2:composite:{intent['jobId']}:"
                    f"{cf4_encode(record['evaluatedParty'])}"
                )
                if (
                    operation.get("payload", {}).get("logicalAddress")
                    != expected_address
                    or operation.get("payload", {}).get("writeCondition")
                    != {"kind": "create-only"}
                ):
                    raise Invalid("Vet storage operation address/write condition mismatch")
            elif operation.get("kind") == "assert-artifact":
                raise Unknown("finalized resolvable Vet AnchorReceipt unavailable")
        if any(
            op.get("payload", {}).get("liveAction") is not None
            for op in intent["operations"][:2]
        ):
            raise Invalid("live Vet action placed inside Work")
        commitment = intent["operations"][3].get("payload", {}).get("artifact")
        if not isinstance(commitment, dict):
            raise Invalid("commitment artifact missing")
        if commitment.get("finalityCommitmentVersion") != "1":
            raise Invalid("commitment artifact discriminator mismatch")
        verify_embedded(commitment, data["publicKeys"], _COMMITMENT_DOMAIN)
        require_signer(commitment, data.get("authenticatedOrchestrator"))
        _verify_commitment_subject(commitment, agreement, intent["jobId"])
        if intent["operations"][3].get("payload", {}).get("logicalAddress") != (
            f"dacs3:commit:{intent['jobId']}"
        ) or intent["operations"][3].get("payload", {}).get("writeCondition") != {
            "kind": "create-only"
        }:
            raise Invalid("signed commitment address/write condition mismatch")
        atomic_receipt = data.get("atomicReceipt")
        if not isinstance(atomic_receipt, dict):
            raise Unknown("common BFT Work receipt unavailable; sequential gate required")
        verify_receipt(
            atomic_receipt, intent, data["publicKeys"], capability=data.get("capability"),
            expected_network_authority=data.get("expectedNetworkAuthority"),
            expected_proof_profile=data.get("expectedProofProfile"),
        )
        timestamp = atomic_receipt["blockRef"]["timestamp"]
        if not isinstance(timestamp, int):
            raise Invalid("consensus block timestamp unavailable")
        _verify_agreement_listing(intent["operations"][2]["payload"]["artifact"], listing, timestamp)
    else:
        purchase_receipt = intent["operations"][0].get("payload", {}).get("receipt")
        if not isinstance(purchase_receipt, dict):
            raise Invalid("Completion does not carry Purchase receipt")
        # The enclosing vector supplies the corresponding Purchase intent.
        prior_intent = data.get("purchaseIntent")
        if not isinstance(prior_intent, dict):
            raise Unknown("Purchase intent unavailable")
        verify_receipt(
            purchase_receipt, prior_intent, data["publicKeys"], capability=data.get("capability"),
            expected_network_authority=data.get("expectedNetworkAuthority"),
            expected_proof_profile=data.get("expectedProofProfile"),
        )
        _profile_shape(prior_intent, "dacs-purchase-v1")
        commitment_projection = data.get("purchaseCommitmentProjection")
        if not isinstance(commitment_projection, dict):
            raise Unknown("finalized Purchase commitment AnchorReceipt unavailable")
        operation_evidence = commitment_projection.get("operationEvidence")
        commitment_leaf = (
            operation_evidence.get("leaf")
            if isinstance(operation_evidence, dict) else None
        )
        if (
            not isinstance(operation_evidence, dict)
            or not isinstance(commitment_leaf, dict)
            or commitment_leaf.get("operationId") != "commitment"
        ):
            raise Invalid("Purchase commitment projection selects the wrong operation")
        evaluate_projection({
            "intent": prior_intent,
            "receipt": purchase_receipt,
            "operationEvidence": operation_evidence,
            "anchorReceipt": commitment_projection.get("anchorReceipt"),
            "publicKeys": data["publicKeys"],
            "capability": data.get("capability"),
            "expectedNetworkAuthority": data.get("expectedNetworkAuthority"),
            "expectedProofProfile": data.get("expectedProofProfile"),
        })
        phases = [
            {"kind": step.get("kind"), "index": i}
            for i, step in enumerate(listing.get("pipeline", []))
            if step.get("kind") == "deliver-storage-program"
        ]
        if len(phases) != 1 or phases[0].get("index") != intent["phaseIndex"]:
            raise Invalid("Completion signed Listing delivery phase mismatch")
        if purchase_receipt.get("paymentSlot", {}).get("key", {}).get("phaseIndex") == intent["phaseIndex"]:
            raise Invalid("Completion delivery phase was substituted for Purchase slot phase")
        delivery = intent["operations"][1].get("payload", {})
        if (
            delivery.get("logicalAddress") != f"dacs4:deliverable:{intent['jobId']}"
            or delivery.get("writeCondition") != {"kind": "create-only"}
        ):
            raise Invalid("Completion delivery address/write condition mismatch")
        if delivery.get("contentHash") != sha256_hex(b64u_decode(delivery.get("bytes", ""))):
            raise Invalid("delivery bytes do not match contentHash")
        agreement = prior_intent["operations"][2].get("payload", {}).get("artifact")
        _verify_agreement(agreement, data["publicKeys"])
        expected_spec = listing.get("offering", {}).get("deliverable")
        expected_ref = agreement.get("terms", {}).get("deliverable", {})
        atomic_delivery = agreement.get("terms", {}).get("additionalTerms", {}).get("atomicDelivery", {})
        if (
            expected_ref.get("deliverableType") != expected_spec.get("kind")
            or expected_ref.get("hash") != sha256_hex(jcs_bytes(expected_spec))
            or delivery.get("logicalAddress") != atomic_delivery.get("logicalAddress")
            or delivery.get("contentHash") != atomic_delivery.get("contentHash")
        ):
            raise Invalid("Completion bytes/pointer do not match verified agreement DeliverableSpec")
        if data.get("claimsEvidenceFinalized") or data.get("claimsBundleFinalized"):
            raise Invalid("Completion inclusion cannot finalize evidence/bundle")


def evaluate_post_purchase(data: dict[str, Any]) -> None:
    remedy = data.get("remedy")
    if remedy == "ordinary-failure-record":
        raise Unknown(
            "a Boolean roleSpecificBundle claim is not verified role-specific evidence"
        )
    elif remedy == "settlement-amendment":
        amendment = data.get("amendment")
        if (
            isinstance(amendment, dict)
            and isinstance(amendment.get("body"), dict)
            and amendment["body"].get("originalEvidenceId")
            not in {None, data.get("originalEvidenceId")}
        ):
            raise Invalid("refund/correction is not linked to original evidence")
        raise Unknown(
            "a versioned SettlementAmendment with verified original publication is unavailable"
        )
    elif remedy == "guaranteed-delivery":
        if data.get("profile") == "dacs-completion-v1":
            raise Invalid("guarantee lacks separately standardized profile")
        raise Unknown("no escrow or delivery-gated Atomic Work profile is standardized")
    else:
        raise Invalid("post-Purchase failure cannot undo original payment")


def _verify_slot_proof(proof: dict[str, Any], public_keys: dict[str, str]) -> None:
    verify_embedded(proof, public_keys, _LEDGER_TEST_DOMAIN)
    if not isinstance(proof.get("key"), dict) or not isinstance(proof.get("state"), dict):
        raise Invalid("slot proof is not structured")


def _tuple_equal(left: dict[str, Any], right: dict[str, Any]) -> bool:
    fields = ("networkId", "railId", "jobId", "phaseIndex")
    return all(type(left.get(k)) is type(right.get(k)) and left.get(k) == right.get(k) for k in fields)


def evaluate_slot(data: dict[str, Any]) -> None:
    proof = data.get("ledgerProof")
    if not isinstance(proof, dict):
        raise Unknown("payment-slot consensus proof unavailable")
    _verify_slot_proof(proof, data["publicKeys"])
    require_signer(proof, _network_authority(data))
    key = data.get("key")
    if not isinstance(key, dict) or not isinstance(key.get("jobId"), str) or not JOB_ID.fullmatch(key["jobId"]):
        raise Invalid("slot jobId is not a canonical uppercase ULID")
    if not _tuple_equal(key, proof["key"]):
        raise Invalid("slot key differs component-wise or by type")
    work = data.get("work", {})
    claim_intent = work.get("intent")
    if not isinstance(claim_intent, dict):
        raise Invalid("slot Work intent unavailable")
    validate_intent(claim_intent)
    if claim_intent.get("profile") != "dacs-purchase-v1":
        raise Invalid("payment slot requires the exact Purchase Work profile")
    _profile_shape(claim_intent, "dacs-purchase-v1")
    agreement = claim_intent["operations"][2].get("payload", {}).get("artifact")
    commitment_op = claim_intent["operations"][3]
    signed_commitment = commitment_op.get("payload", {}).get("artifact")
    slot_op = next((op for op in claim_intent["operations"] if op["kind"] == "payment-slot-cas"), None)
    transfer = next((op for op in claim_intent["operations"] if op["kind"] == "native-dem-transfer"), None)
    authority = data.get("slotAuthority")
    if not isinstance(authority, dict):
        raise Unknown("authenticated slot-conflict authority unavailable")
    payment_input = authority.get("paymentPhaseInput")
    authority_agreement = authority.get("agreement")
    payer_bundle = authority.get("payerBundle")
    payee_bundle = authority.get("payeeBundle")
    rail_definition = authority.get("railDefinition")
    commitment = authority.get("finalityCommitment")
    commitment_receipt = authority.get("commitmentReceipt")
    if not all(isinstance(v, dict) for v in (
        agreement, signed_commitment, slot_op, transfer, payment_input, authority_agreement,
        payer_bundle, payee_bundle, rail_definition, commitment, commitment_receipt,
    )):
        raise Unknown("verified agreement/payment inputs unavailable for slot digest")
    _verify_agreement(agreement, data["publicKeys"])
    _verify_agreement(authority_agreement, data["publicKeys"])
    _verify_identity_bundle(payer_bundle, data["publicKeys"])
    _verify_identity_bundle(payee_bundle, data["publicKeys"])
    _verify_artifact(rail_definition, data["publicKeys"])
    require_signer(rail_definition, _network_authority(data))
    _verify_finality_commitment(commitment, commitment_receipt, data["publicKeys"])
    if commitment != signed_commitment:
        raise Invalid("presented commitment differs from signed Work operation artifact")
    _verify_commitment_subject(commitment, agreement, claim_intent["jobId"])
    if commitment_op.get("payload", {}).get("logicalAddress") != (
        f"dacs3:commit:{claim_intent['jobId']}"
    ):
        raise Invalid("signed commitment logical address does not bind Work jobId")
    if authority_agreement != agreement or payment_input.get("agreement") != agreement:
        raise Invalid("PaymentPhaseInput does not carry the verified signed Agreement")
    if payment_input.get("jobId") != claim_intent["jobId"]:
        raise Invalid("PaymentPhaseInput job mismatch")
    payer = payment_input.get("payer", {})
    payee = payment_input.get("payee", {})
    agreement_parties = {
        party.get("role"): party
        for party in agreement.get("parties", [])
        if isinstance(party, dict)
    }
    buyer_party = agreement_parties.get("buyer", {})
    seller_party = agreement_parties.get("seller", {})
    if (
        payer.get("bundleHash") != _identity_bundle_hash(payer_bundle)
        or payer.get("primaryClaim") != payer_bundle.get("presentedBy")
        or payer.get("payingKey") not in [c.get("ref") for c in payer_bundle.get("claims", [])]
        or payee.get("bundleHash") != _identity_bundle_hash(payee_bundle)
        or payee.get("primaryClaim") != payee_bundle.get("presentedBy")
        or payer.get("bundleHash") != buyer_party.get("bundleHash")
        or payer.get("primaryClaim") != buyer_party.get("primaryClaim")
        or payee.get("bundleHash") != seller_party.get("bundleHash")
        or payee.get("primaryClaim") != seller_party.get("primaryClaim")
        or payment_input.get("rail") != rail_definition.get("body")
        or payment_input.get("amount") != agreement.get("terms", {}).get("price")
    ):
        raise Invalid("PaymentPhaseInput is not bound to verified bundles, rail, and agreement")
    payer_account = _bundle_native_account(
        payer_bundle, payer.get("payingKey"), "payer"
    )
    payee_account = _bundle_native_account(
        payee_bundle, payee.get("primaryClaim"), "payee"
    )
    roster = {
        binding.get("role"): binding
        for binding in claim_intent.get("roleRoster", [])
        if isinstance(binding, dict)
    }
    payer_roster = roster.get("payer", {})
    payee_roster = roster.get("seller", {})
    if (
        payer_roster.get("signer") != payer.get("payingKey")
        or payer_roster.get("nativeAccount") != payer_account
        or payee_roster.get("signer") != payee.get("primaryClaim")
        or (
            "nativeAccount" in payee_roster
            and payee_roster.get("nativeAccount") != payee_account
        )
        or payee.get("payeeAddress") != payee_account
    ):
        raise Invalid("signed roster/payment input contradicts authenticated native accounts")
    conflict = {
        **{field: key[field] for field in ("networkId", "railId", "jobId", "phaseIndex")},
        "agreementHash": _agreement_hash(agreement),
        "commitmentLogicalAddress": commitment_op.get("payload", {}).get("logicalAddress"),
        "payer": payer_account,
        "payee": payee_account,
        "asset": rail_definition.get("body", {}).get("asset"),
        "amount": agreement.get("terms", {}).get("price", {}).get("amount"),
    }
    transfer_payload = transfer["payload"]
    if (
        transfer_payload.get("from") != conflict["payer"]
        or transfer_payload.get("to") != conflict["payee"]
        or transfer_payload.get("asset") != conflict["asset"]
        or transfer_payload.get("amount") != conflict["amount"]
    ):
        raise Invalid("signed native transfer contradicts verified slot conflict tuple")
    digest = conflict_digest(conflict)
    slot_payload = slot_op["payload"]
    if (
        slot_payload.get("slotKey") != key
        or slot_payload.get("conflictDigest") != digest
        or data.get("conflictDigest") != digest
    ):
        raise Invalid("conflict digest mismatch")
    state = proof["state"]
    action = data.get("action")
    if action == "claim":
        if work.get("workId") != work_id(claim_intent):
            raise Invalid("slot claim workId does not derive from intent")
        if not _tuple_equal(key, claim_intent):
            raise Invalid("slot claim intent tuple mismatch")
        op_ids = [operation["operationId"] for operation in claim_intent["operations"]]
        if "payment-slot" not in op_ids or "payment" not in op_ids:
            raise Invalid("slot/payment operation missing")
        slot_index, payment_index = op_ids.index("payment-slot"), op_ids.index("payment")
        payment_op = claim_intent["operations"][payment_index]
        if (
            slot_index >= payment_index
            or payment_op.get("kind") != "native-dem-transfer"
            or "payment-slot" not in payment_op.get("dependsOn", [])
        ):
            raise Invalid("signed Work does not CAS slot before payment")
        if slot_payload.get("expected") != {
            "state": state.get("state"), "generation": state.get("generation")
        }:
            raise Invalid("signed slot expected state/generation mismatch")
        if state.get("state") != "vacant":
            if state.get("conflictDigest") != digest:
                raise Invalid("occupied slot conflict")
            raise Invalid("occupied slot requires replay/reconcile")
        new_state = data.get("newState", {})
        if (
            new_state.get("state") != "in-flight"
            or new_state.get("generation") != state.get("generation")
            or new_state.get("workId") != work.get("workId")
            or new_state.get("conflictDigest") != digest
        ):
            raise Invalid("invalid claim CAS transition")
    elif action == "replay":
        if state.get("workId") != work.get("workId") or state.get("conflictDigest") != digest:
            raise Invalid("replay is not exact")
        if data.get("executesTransfer"):
            raise Invalid("replay executes another transfer")
        if state.get("state") == "settled" and data.get("returnedReceiptCommitment") != state.get("receiptCommitment"):
            raise Invalid("settled replay did not return receipt")
    elif action == "retry":
        if state.get("state") != "rolled-back":
            if data.get("attemptObservation") in {"not-found", "timeout", "indeterminate"}:
                raise Unknown("indeterminate attempt keeps slot held")
            raise Invalid("retry without terminal rollback")
        new_state = data.get("newState", {})
        retry_intent = work.get("intent")
        if not isinstance(retry_intent, dict):
            raise Invalid("retry Work intent unavailable")
        validate_intent(retry_intent)
        failure_receipt = data.get("failureReceipt")
        failure_intent = data.get("failureIntent")
        if not isinstance(failure_receipt, dict) or not isinstance(failure_intent, dict):
            raise Unknown("rolled-back failure Work receipt unavailable")
        verify_receipt(
            failure_receipt, failure_intent, data["publicKeys"], capability=data.get("capability"),
            expected_network_authority=data.get("expectedNetworkAuthority"),
            expected_proof_profile=data.get("expectedProofProfile"),
        )
        failure_slot = failure_receipt.get("paymentSlot", {})
        if (
            new_state.get("generation") != state.get("generation", -1) + 1
            or new_state.get("conflictDigest") != digest
            or new_state.get("workId") == state.get("workId")
            or retry_intent.get("priorFailureReceiptCommitment") != state.get("failureReceiptCommitment")
            or failure_receipt.get("outcome") != "rolled-back"
            or failure_receipt.get("receiptCommitment") != state.get("failureReceiptCommitment")
            or failure_slot.get("key") != key
            or failure_slot.get("after", {}).get("generation") != state.get("generation")
            or failure_slot.get("after") != state
            or work.get("workId") != work_id(retry_intent)
            or retry_intent.get("networkId") != key.get("networkId")
            or retry_intent.get("railId") != key.get("railId")
            or retry_intent.get("jobId") != key.get("jobId")
            or retry_intent.get("phaseIndex") != key.get("phaseIndex")
        ):
            raise Invalid("retry generation is not bound to failure receipt")
    elif action == "observe":
        if data.get("attemptObservation") in {"not-found", "timeout", "indeterminate"}:
            raise Unknown("unresolved observation keeps slot held")
    else:
        raise Invalid("unknown slot transition action")
    # SessionStore is intentionally ignored; only a vector claiming that it
    # overrode the proven ledger is rejected.
    if data.get("sessionStoreAuthoritative") is True:
        raise Invalid("SessionStore cannot override slot ledger")


def evaluate_slot_distinction(data: dict[str, Any]) -> None:
    left, right = data["leftKey"], data["rightKey"]
    if _tuple_equal(left, right):
        raise Invalid("keys are not distinct")
    if data.get("displayKeyLeft") == data.get("displayKeyRight") and data.get("treatedAsSame"):
        raise Invalid("concatenated display collision controlled slot equality")


def _verify_atomic_publication(
    publication: dict[str, Any] | None, evidence: dict[str, Any], address: str,
    public_keys: dict[str, str], *, network_authority: str,
    network_id: str, proof_profile: str,
) -> None:
    if not isinstance(publication, dict):
        raise Unknown("finalized Atomic evidence publication unavailable")
    canonical_bytes = jcs_bytes(evidence)
    try:
        supplied_bytes = b64u_decode(publication.get("canonicalBytes", ""))
    except Invalid as exc:
        raise Invalid("Atomic publication canonical bytes are invalid") from exc
    if supplied_bytes != canonical_bytes:
        raise Invalid("Atomic publication bytes differ from complete signed evidence")
    mode = publication.get("mode")
    if mode == "replay":
        try:
            existing_bytes = b64u_decode(
                publication.get("existingCanonicalBytes", "")
            )
        except Invalid as exc:
            raise Invalid("existing Atomic publication bytes are invalid") from exc
        if existing_bytes != canonical_bytes:
            raise Invalid("Atomic publication replay is not byte-identical")
    elif mode != "create-only":
        raise Invalid("Atomic publication is neither create-only nor exact replay")
    anchor = publication.get("anchorReceipt")
    required_anchor_fields = {
        "receiptVersion", "substrate", "finalityProfile", "logicalAddress",
        "nativeAddress", "contentHash", "transactionRef", "writer", "nonce",
        "state", "observationDisposition", "observedAt", "blockRef", "evidence",
    }
    if not isinstance(anchor, dict):
        raise Unknown("Atomic publication AnchorReceipt unavailable")
    if "evidence" not in anchor:
        raise Unknown("Atomic publication lifecycle proof unavailable")
    if set(anchor) != required_anchor_fields:
        raise Invalid("Atomic publication AnchorReceipt is incomplete")
    content_hash = sha256_hex(canonical_bytes)
    if (
        anchor.get("receiptVersion") != "1"
        or anchor.get("substrate") != network_id
        or anchor.get("finalityProfile") != proof_profile
        or anchor.get("logicalAddress") != address
        or anchor.get("contentHash") != content_hash
        or anchor.get("state") != "finalized"
        or anchor.get("observationDisposition") != "established"
        or not isinstance(anchor.get("nativeAddress"), str)
        or not anchor["nativeAddress"]
        or not isinstance(anchor.get("writer"), str)
        or not anchor["writer"]
        or not isinstance(anchor.get("nonce"), str)
        or not anchor["nonce"]
        or not isinstance(anchor.get("transactionRef"), dict)
        or set(anchor["transactionRef"]) != {"kind", "value"}
        or not all(
            isinstance(anchor["transactionRef"].get(field), str)
            and anchor["transactionRef"][field]
            for field in ("kind", "value")
        )
        or not isinstance(anchor.get("blockRef"), dict)
        or not isinstance(anchor.get("observedAt"), int)
        or isinstance(anchor.get("observedAt"), bool)
    ):
        raise Invalid("Atomic publication AnchorReceipt binding mismatch")
    proof = verify_encoded_evidence(
        anchor["evidence"], "test-anchor-publication", public_keys,
        _PUBLICATION_TEST_DOMAIN, expected_signer=network_authority,
    )
    expected_proof = {
        "logicalAddress": address,
        "nativeAddress": anchor["nativeAddress"],
        "contentHash": content_hash,
        "transactionRef": anchor["transactionRef"],
        "writer": anchor["writer"],
        "nonce": anchor["nonce"],
        "state": "finalized",
        "blockRef": anchor["blockRef"],
        "proofProfile": proof_profile,
    }
    if any(proof.get(field) != value for field, value in expected_proof.items()):
        raise Invalid("Atomic publication lifecycle proof subject mismatch")


def verify_settlement(data: dict[str, Any]) -> None:
    evidence = data.get("evidence")
    if not isinstance(evidence, dict):
        raise Unknown("Atomic settlement evidence unavailable")
    has_atomic = "atomicEvidenceVersion" in evidence
    has_legacy = "evidenceVersion" in evidence
    if has_atomic == has_legacy:
        raise Invalid("Atomic/legacy evidence discriminator must be exactly one")
    if evidence.get("atomicEvidenceVersion") != "1" or "kind" in evidence:
        raise Invalid("legacy transaction reference is not Atomic settlement evidence")
    verify_embedded(evidence, data["publicKeys"], EVIDENCE_DOMAIN)
    authority = data.get("authority")
    if not isinstance(authority, dict):
        raise Unknown("verified phase authority unavailable")
    commitment = authority.get("finalityCommitment")
    commitment_receipt = authority.get("commitmentReceipt")
    session = authority.get("sessionContext")
    if not all(isinstance(v, dict) for v in (commitment, commitment_receipt, session)):
        raise Unknown("finalized commitment and SessionContext unavailable")
    _verify_finality_commitment(commitment, commitment_receipt, data["publicKeys"])
    phase_orchestrator = claim_key(commitment.get("signature", {}).get("signer"))
    session_orchestrators = [p.get("primaryClaim") for p in session.get("parties", []) if p.get("role") == "orchestrator"]
    if session_orchestrators != [phase_orchestrator]:
        raise Invalid("phase orchestrator does not match authenticated SessionContext")
    if claim_key(evidence.get("signature", {}).get("signer")) != phase_orchestrator:
        raise Invalid("evidence signer is not authenticated phase orchestrator")
    receipt = data.get("receipt")
    intent = data.get("intent")
    if not isinstance(receipt, dict) or not isinstance(intent, dict):
        raise Unknown("Work receipt/proof unavailable")
    verify_receipt(
        receipt, intent, data["publicKeys"], capability=data.get("capability"),
        purchase_intent=data.get("purchaseIntent"), purchase_receipt=data.get("purchaseReceipt"),
        expected_network_authority=data.get("expectedNetworkAuthority"),
        expected_proof_profile=data.get("expectedProofProfile"),
    )
    for field in ("networkId", "jobId", "railId", "phaseIndex"):
        if type(evidence.get(field)) is not type(intent.get(field)) or evidence.get(field) != intent.get(field):
            raise Invalid(f"settlement evidence {field} does not match verified Work intent")
    receipt_ref = evidence.get("workReceiptRef")
    if not isinstance(receipt_ref, dict):
        raise Unknown("Work receipt reference unavailable")
    expected_receipt_hash = receipt_hash(receipt)
    expected_receipt_ref = {
        "refVersion": "1",
        "networkId": receipt["networkId"],
        "workId": receipt["workId"],
        "receiptCommitment": receipt["receiptCommitment"],
        "contentHash": expected_receipt_hash,
        "locator": {"kind": "demos-work-receipt-v1", "value": receipt["workId"]},
    }
    locator = receipt_ref.get("locator")
    if (
        any(
            receipt_ref.get(field) != expected_receipt_ref[field]
            for field in (
                "refVersion", "networkId", "workId", "receiptCommitment",
                "contentHash",
            )
        )
        or not isinstance(locator, dict)
        or locator.get("kind") != expected_receipt_ref["locator"]["kind"]
        or locator.get("value") != expected_receipt_ref["locator"]["value"]
    ):
        raise Invalid("Atomic Work receipt reference mismatch")
    context = data.get("authenticatedContext")
    if not isinstance(context, dict):
        raise Unknown("authenticated agreement/phase context unavailable")
    for field in ("networkId", "jobId", "railId", "phaseIndex"):
        if type(evidence.get(field)) is not type(context.get(field)) or evidence.get(field) != context.get(field):
            raise Invalid(f"settlement evidence {field} does not match authenticated context")
    if (
        context.get("jobId") != commitment.get("jobId")
        or context.get("jobId") != session.get("jobId")
        or context.get("networkId") != intent.get("networkId")
        or context.get("railId") != intent.get("railId")
        or context.get("phaseIndex") != intent.get("phaseIndex")
    ):
        raise Invalid("authenticated settlement context contradicts verified sources")
    if not isinstance(evidence.get("jobId"), str) or not JOB_ID.fullmatch(evidence["jobId"]):
        raise Invalid("settlement evidence jobId is not a canonical uppercase ULID")
    operation_ref = evidence.get("operationRef")
    proof = evidence.get("operationProof")
    if not isinstance(operation_ref, dict) or not isinstance(proof, dict):
        raise Unknown("operation reference/proof unavailable")
    subject = proof.get("subject")
    if not isinstance(subject, dict):
        raise Unknown("operation proof subject unavailable")
    index = operation_ref.get("operationIndex")
    if not isinstance(index, int) or isinstance(index, bool) or not (0 <= index < len(receipt["operationResults"])):
        raise Invalid("operation reference index invalid")
    leaf = receipt["operationResults"][index]
    expected_ref = {
        "kind": "demos-work-operation-v1",
        "networkId": receipt["networkId"],
        "workId": receipt["workId"],
        "operationIndex": index,
        "operationId": leaf["operationId"],
        "operationKind": leaf["operationKind"],
    }
    if any(
        operation_ref.get(field) != value
        for field, value in expected_ref.items()
    ):
        raise Invalid("settlement operation reference mismatch")
    expected_subject = {
        "networkId": receipt["networkId"],
        "workId": receipt["workId"],
        "winningAttemptId": receipt["winningAttempt"]["attemptId"],
        "operationReceiptRoot": receipt["operationReceiptRoot"],
        "operationIndex": index,
        "operationId": leaf["operationId"],
        "operationKind": leaf["operationKind"],
        "receiptContentHash": expected_receipt_hash,
    }
    if any(subject.get(key) != value for key, value in expected_subject.items()):
        raise Invalid("operation proof subject required member mismatch")
    try:
        decoded_path = json.loads(b64u_decode(proof.get("value", "")).decode("utf-8"))
    except (Invalid, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise Invalid("operation proof value encoding invalid") from exc
    capability = data.get("capability")
    if not isinstance(capability, dict):
        raise Unknown("verified proof-profile capability unavailable")
    verify_capability(capability, data["publicKeys"], data.get("expectedNetworkAuthority"))
    if proof.get("proofProfile") != capability.get("proofProfile"):
        raise Invalid("unsupported operation proof profile")
    if not isinstance(decoded_path, list) or not verify_inclusion(
        leaf, decoded_path, receipt["operationReceiptRoot"]
    ):
        raise Invalid("operation receipt inclusion path invalid")
    outcome = evidence.get("outcome")
    if outcome == "success":
        if leaf.get("status") != "committed" or receipt.get("outcome") != "committed":
            raise Invalid("success evidence does not select a committed operation")
    elif outcome == "failure":
        if not isinstance(evidence.get("reason"), str) or not evidence["reason"]:
            raise Invalid("failure evidence reason missing")
        if receipt.get("outcome") != "rolled-back" or leaf.get("status") not in {
            "rolled-back", "not-executed"
        }:
            raise Invalid("failure evidence does not select a rollback operation")
        forbidden = {
            "paymentAmount", "deliverableContentHash", "deliverableAnchor",
            "settlementFinality",
        }
        if forbidden & set(evidence):
            raise Invalid("failure evidence carries success-only members")
    else:
        raise Invalid("unsupported Atomic evidence outcome")
    expected_kind = "native-dem-transfer" if evidence.get("phase") == "pay-dem" else "storage-program-put"
    if leaf.get("operationKind") != expected_kind:
        raise Invalid("settlement phase/operation kind mismatch")
    if evidence.get("phase") == "pay-dem":
        pc2 = parse_pc2_address(data.get("pc2Address"))
        for field in ("jobId", "railId", "phaseIndex"):
            if type(evidence.get(field)) is not type(pc2.get(field)) or evidence.get(field) != pc2.get(field):
                raise Invalid(f"settlement evidence {field} does not match PC2 address")
        slot_key = receipt.get("paymentSlot", {}).get("key", {})
        for field in ("networkId", "jobId", "railId", "phaseIndex"):
            if type(evidence.get(field)) is not type(slot_key.get(field)) or evidence.get(field) != slot_key.get(field):
                raise Invalid(f"settlement evidence {field} does not match receipt slot")
        if outcome == "success":
            payment = evidence.get("paymentAmount")
            operation_payload = intent["operations"][index]["payload"]
            if payment != {"amount": operation_payload.get("amount"), "currency": operation_payload.get("asset")}:
                raise Invalid("paymentAmount does not match payment operation")
            if evidence.get("settlementFinality", {}).get("model") != "bft-final":
                raise Invalid("payment settlement finality is not BFT-final")
    else:
        storage = leaf.get("storageOutput")
        if outcome == "success" and not isinstance(storage, dict):
            raise Invalid("delivery settlement operation lacks storage output")
        if outcome == "success":
            if evidence.get("deliverableContentHash") != storage.get("contentHash"):
                raise Invalid("deliverable content hash mismatch")
            anchor = evidence.get("deliverableAnchor")
            if anchor != {"kind": "storage-program", "locator": storage.get("logicalAddress")}:
                raise Invalid("deliverable anchor mismatch")
    claimed_id = data.get("settlementId")
    if claimed_id != settlement_id(operation_ref):
        raise Invalid("Atomic settlement identity mismatch")
    generation = None
    if evidence.get("phase") == "pay-dem":
        generation = receipt.get("paymentSlot", {}).get("after", {}).get("generation")
        if not isinstance(generation, int) or isinstance(generation, bool) or generation < 0:
            raise Invalid("verified receipt slot generation unavailable")
    evidence_address = data.get("evidenceAddress")
    verify_atomic_evidence_address(evidence_address, evidence, generation)
    _verify_atomic_publication(
        data.get("auditPublication"), evidence, evidence_address,
        data["publicKeys"],
        network_authority=claim_key(capability["networkAuthority"]),
        network_id=intent["networkId"],
        proof_profile=data.get("expectedProofProfile"),
    )
    if data.get("auditWrite", {}).get("resubmitsPayment"):
        raise Invalid("audit tail resubmits payment")


def evaluate_role_anchor(data: dict[str, Any]) -> None:
    if data.get("finalisesFromCompletionReceiptOnly"):
        raise Invalid("Completion receipt alone cannot finalize DACS-5")
    if data.get("bundleAuthoredInsideCompletion"):
        raise Invalid("receipt-dependent bundle cannot be authored in Completion Work")
    if data.get("workCarriedBundleProfile") != "standardized":
        raise Unknown(
            "v1 Purchase/Completion profiles cannot carry a receipt-dependent DACS-5 bundle; "
            "a later Work profile is not standardized"
        )
    purchase_intent = data.get("purchaseIntent")
    completion_intent = data.get("completionIntent")
    purchase_receipt = data.get("purchaseReceipt")
    completion_receipt = data.get("completionReceipt")
    if not all(isinstance(value, dict) for value in (
        purchase_intent, completion_intent, purchase_receipt, completion_receipt
    )):
        raise Unknown("Purchase and Completion intent/receipt evidence is required")
    if purchase_intent.get("profile") != "dacs-purchase-v1" or completion_intent.get("profile") != "dacs-completion-v1":
        raise Invalid("role anchor Work profiles mismatch")
    verify_receipt(
        purchase_receipt, purchase_intent, data["publicKeys"], capability=data.get("capability"),
        expected_network_authority=data.get("expectedNetworkAuthority"),
        expected_proof_profile=data.get("expectedProofProfile"),
    )
    verify_receipt(
        completion_receipt, completion_intent, data["publicKeys"],
        capability=data.get("capability"), purchase_intent=purchase_intent,
        purchase_receipt=purchase_receipt,
        expected_network_authority=data.get("expectedNetworkAuthority"),
        expected_proof_profile=data.get("expectedProofProfile"),
    )
    embedded_purchase = completion_intent.get("operations", [{}])[0].get("payload", {}).get("receipt")
    if embedded_purchase != purchase_receipt:
        raise Invalid("Completion Work does not bind verified Purchase receipt")
    for field in ("networkId", "railId", "jobId"):
        if purchase_intent.get(field) != completion_intent.get(field):
            raise Invalid(f"Purchase/Completion {field} mismatch")
    agreement = data.get("agreement")
    bundle_party_map = data.get("bundlePartyMap")
    if not isinstance(agreement, dict) or not isinstance(bundle_party_map, dict):
        raise Unknown("verified agreement and bundle party map required")
    _verify_artifact(agreement, data["publicKeys"])
    if agreement.get("body", {}).get("jobId") != completion_intent["jobId"]:
        raise Invalid("agreement jobId mismatch")
    intent = completion_intent
    receipt = completion_receipt
    authorizations = data.get("completionAuthorizations")
    if not isinstance(authorizations, list):
        raise Unknown("operation authorization unavailable")
    verify_authorizations(
        intent, authorizations, data["publicKeys"], data.get("authorizationAuthority"),
        data.get("capability"), data.get("expectedNetworkAuthority"),
        data.get("expectedProofProfile"),
    )
    anchor = data.get("roleAnchor")
    if not isinstance(anchor, dict):
        raise Unknown("role anchor unavailable")
    binding = anchor.get("bundleBinding")
    if not isinstance(binding, dict):
        raise Unknown("BundleBinding unavailable")
    verify_embedded(binding, data["publicKeys"], _BINDING_TEST_DOMAIN)
    role = anchor.get("role")
    roster = {r["role"]: r["signer"] for r in intent["roleRoster"]}
    signer_claim = claim_key(roster.get(role))
    agreement_holder = agreement.get("body", {}).get("parties", {}).get(role)
    bundle_holder = bundle_party_map.get(role)
    if signer_claim != agreement_holder or signer_claim != bundle_holder:
        raise Invalid("Work role signer does not match agreement and bundle party map")
    if claim_key(binding.get("signature", {}).get("signer")) != signer_claim:
        raise Invalid("BundleBinding signer does not hold anchored role")
    operation_id = anchor.get("operationRef", {}).get("operationId")
    leaves = [r for r in receipt["operationResults"] if r["operationId"] == operation_id]
    if len(leaves) != 1 or leaves[0].get("status") != "committed":
        raise Invalid("role anchor operation not committed")
    storage = leaves[0].get("storageOutput")
    if not isinstance(storage, dict):
        raise Invalid("role anchor lacks storage receipt")
    for field in ("logicalAddress", "contentHash"):
        if anchor.get(field) != storage.get(field) or binding.get(field) != storage.get(field):
            raise Invalid(f"role anchor {field} mismatch")
    if binding.get("jobId") != intent["jobId"] or binding.get("role") != role:
        raise Invalid("BundleBinding tuple mismatch")
    if anchor.get("anchoredByRole") != role:
        raise Invalid("anchoredByRole mismatch")
    if data.get("roleSource") == "outer-submitter":
        raise Invalid("outer submitter/native writer cannot establish DACS role")
def evaluate_audit(data: dict[str, Any]) -> None:
    operations = data.get("operations")
    if not isinstance(operations, list):
        raise Invalid("audit operations missing")
    if any(op.get("kind") in {"native-dem-transfer", "payment-slot-cas"} for op in operations):
        raise Invalid("audit/repair tail contains payment operation")
    purchase_intent = data.get("purchaseIntent")
    purchase_receipt = data.get("purchaseReceipt")
    completion_intent = data.get("completionIntent")
    completion_receipt = data.get("completionReceipt")
    if not all(isinstance(value, dict) for value in (
        purchase_intent, purchase_receipt, completion_intent,
        completion_receipt,
    )):
        raise Unknown("authenticated Purchase and Completion evidence unavailable")
    verify_receipt(
        purchase_receipt, purchase_intent, data["publicKeys"],
        capability=data.get("capability"),
        expected_network_authority=data.get("expectedNetworkAuthority"),
        expected_proof_profile=data.get("expectedProofProfile"),
    )
    verify_receipt(
        completion_receipt, completion_intent, data["publicKeys"],
        capability=data.get("capability"), purchase_intent=purchase_intent,
        purchase_receipt=purchase_receipt,
        expected_network_authority=data.get("expectedNetworkAuthority"),
        expected_proof_profile=data.get("expectedProofProfile"),
    )
    if (
        purchase_intent.get("profile") != "dacs-purchase-v1"
        or completion_intent.get("profile") != "dacs-completion-v1"
        or completion_intent.get("operations", [{}])[0].get("payload", {}).get("receipt")
        != purchase_receipt
    ):
        raise Invalid("audit tail does not bind the verified Purchase/Completion pair")
    proofs = data.get("dependencyProofs")
    if not isinstance(proofs, list):
        raise Unknown("audit dependency proofs unavailable")
    works = {
        "purchase": (purchase_intent, purchase_receipt),
        "completion": (completion_intent, completion_receipt),
    }
    expected_keys = {
        (label, index)
        for label, (_, receipt) in works.items()
        for index in range(len(receipt["operationResults"]))
    }
    seen: set[tuple[str, int]] = set()
    for proof in proofs:
        if not isinstance(proof, dict):
            raise Invalid("audit dependency proof is not structured")
        label = proof.get("work")
        index = proof.get("operationIndex")
        if (
            label not in works
            or not isinstance(index, int)
            or isinstance(index, bool)
            or (label, index) not in expected_keys
            or (label, index) in seen
        ):
            raise Invalid("audit dependency proof selection is invalid")
        seen.add((label, index))
        _, receipt = works[label]
        leaf = receipt["operationResults"][index]
        operation_ref = proof.get("operationRef")
        expected_ref = {
            "kind": "demos-work-operation-v1",
            "networkId": receipt["networkId"],
            "workId": receipt["workId"],
            "operationIndex": index,
            "operationId": leaf["operationId"],
            "operationKind": leaf["operationKind"],
        }
        if (
            not isinstance(operation_ref, dict)
            or any(operation_ref.get(field) != value for field, value in expected_ref.items())
            or proof.get("receiptContentHash") != receipt_hash(receipt)
            or proof.get("leaf") != leaf
            or not isinstance(proof.get("inclusionPath"), list)
            or not verify_inclusion(
                leaf, proof["inclusionPath"], receipt["operationReceiptRoot"]
            )
        ):
            raise Invalid("audit dependency proof does not bind a finalized Work operation")
    if seen != expected_keys:
        raise Unknown("audit dependency proof set is incomplete")
    if (
        data.get("sessionStateBefore") != "audit-pending"
        or data.get("sessionStateAfter") != "finalised"
    ):
        raise Invalid("audit tail session-state transition is invalid")
    identities = [op.get("idempotencyKey") for op in operations]
    if any(not isinstance(value, str) or not value for value in identities):
        raise Invalid("audit operation lacks idempotency key")
    if len(identities) != len(set(identities)) and data.get("duplicateEffectCount", 0) > 0:
        raise Invalid("audit replay produced duplicate effect")
    prior = data.get("priorAnchor")
    replay = data.get("replayAnchor")
    if prior is not None or replay is not None:
        if not isinstance(prior, dict) or not isinstance(replay, dict):
            raise Unknown("authenticated audit anchor reconciliation unavailable")
        for field in ("logicalAddress", "contentHash", "canonicalBytes"):
            if replay.get(field) != prior.get(field):
                raise Invalid(f"audit replay changed immutable {field}")
        lifecycle = data.get("lifecycleEvidence")
        if not isinstance(lifecycle, dict):
            raise Unknown("audit replay lifecycle evidence unavailable")
        _verify_ledger_evidence(
            lifecycle, data["publicKeys"], _network_authority(data),
            data.get("nativeTransactionRef"),
        )


def evaluate_limits(data: dict[str, Any]) -> None:
    capability = data["capability"]
    intent = data["intent"]
    consume_capability_for_intent(
        intent, capability, data["publicKeys"], data.get("expectedNetworkAuthority"),
        data.get("expectedProofProfile"),
    )
    limits = capability["limits"]
    if len(jcs_bytes(intent)) > limits["maxCanonicalBytes"]:
        raise Invalid("canonical Work exceeds node byte limit")
    if len(intent["operations"]) > limits["maxOperations"]:
        raise Invalid("Work exceeds node operation limit")
    if data.get("executionTimeMs", 0) > limits["maxExecutionTimeMs"]:
        raise Invalid("Work exceeds node execution-time limit")
    proof_material = data.get("proofMaterial")
    if proof_material is None:
        raise Unknown("proof material unavailable for node proof-byte enforcement")
    if not _is_pure_json(proof_material):
        raise Invalid("proof material is not canonical safe-integer JSON")
    if len(jcs_bytes(proof_material)) > limits["maxProofBytes"]:
        raise Invalid("canonical proof material exceeds node proof-byte limit")
    if data.get("checkedBy") != "node":
        raise Invalid("client-only limit check")
    if data.get("authoritativeSource") != "consensus":
        raise Invalid("client-generated status/receipt treated as authoritative")
    prior = data.get("priorAuthenticatedState")
    later = data.get("laterObservation")
    if later == "indeterminate" and data.get("retainedState") != prior:
        raise Invalid("indeterminate observation overwrote authenticated state")


def evaluate_expiry(data: dict[str, Any]) -> None:
    intent = data["intent"]
    validate_intent(intent)
    consensus_time = data.get("consensusTransitionTime")
    if not isinstance(consensus_time, int) or isinstance(consensus_time, bool):
        raise Unknown("authenticated consensus transition time unavailable")
    if consensus_time >= intent["expiresAt"]:
        raise Invalid("Work expired before its first operation")
    if data.get("executedOperationCount", 0) < 1:
        raise Invalid("valid Work did not execute as modeled")


